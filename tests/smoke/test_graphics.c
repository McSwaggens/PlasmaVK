static void submit(VkCommandBuffer cb)
{
    VkSubmitInfo info;
    vkEndCommandBuffer(cb);
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
    info.commandBufferCount = 1;
    info.pCommandBuffers = &cb;
    CHECK_VK(vkQueueSubmit(queue, 1, &info, VK_NULL_HANDLE), VK_SUCCESS);
    CHECK_VK(vkQueueWaitIdle(queue), VK_SUCCESS);
    vkFreeCommandBuffers(device, cmd_pool, 1, &cb);
}

/* Everything before against everything after. */
static void barrier(VkCommandBuffer cb)
{
    VkMemoryBarrier2 mb;
    VkDependencyInfo dep;
    memset(&mb, 0, sizeof(mb));
    mb.sType = VK_STRUCTURE_TYPE_MEMORY_BARRIER_2;
    mb.srcStageMask = VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT;
    mb.srcAccessMask = VK_ACCESS_2_MEMORY_WRITE_BIT;
    mb.dstStageMask = VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT;
    mb.dstAccessMask = VK_ACCESS_2_MEMORY_READ_BIT | VK_ACCESS_2_MEMORY_WRITE_BIT;
    memset(&dep, 0, sizeof(dep));
    dep.sType = VK_STRUCTURE_TYPE_DEPENDENCY_INFO;
    dep.memoryBarrierCount = 1;
    dep.pMemoryBarriers = &mb;
    vkCmdPipelineBarrier2(cb, &dep);
}

/* Copies one aspect of a layer to b (tightly packed), after a barrier. */
static void download(VkCommandBuffer cb, const struct img *m, uint32_t layer, VkImageAspectFlags aspect, const struct buf *b)
{
    VkBufferImageCopy r;
    barrier(cb);
    memset(&r, 0, sizeof(r));
    r.imageSubresource.aspectMask = aspect;
    r.imageSubresource.baseArrayLayer = layer;
    r.imageSubresource.layerCount = 1;
    r.imageExtent.width = m->w;
    r.imageExtent.height = m->h;
    r.imageExtent.depth = 1;
    vkCmdCopyImageToBuffer(cb, m->image, VK_IMAGE_LAYOUT_GENERAL, b->buffer, 1, &r);
    barrier(cb);
}

static VkShaderModule shader(const uint32_t *code, size_t size)
{
    VkShaderModuleCreateInfo info;
    VkShaderModule m = VK_NULL_HANDLE;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
    info.codeSize = size;
    info.pCode = code;
    vkCreateShaderModule(device, &info, NULL, &m);
    return m;
}

/* ---- Pipelines ---- */

struct pipe {
    const uint32_t *vs, *fs;
    size_t vs_size, fs_size;
    VkPipelineLayout layout;
    VkPrimitiveTopology topology;
    VkBool32 restart;
    uint32_t colors;
    VkFormat color_formats[4], depth_format, stencil_format;
    VkSampleCountFlagBits samples;
    VkRenderPass rp;
    uint32_t subpass;
    const VkPipelineVertexInputStateCreateInfo *vertex;
    VkPipelineColorBlendAttachmentState blend[4]; /* used with has_blend */
    bool has_blend;
    float blend_constants[4];
    VkPipelineDepthStencilStateCreateInfo ds; /* used with has_ds */
    bool has_ds;
    VkCullModeFlags cull;
    VkFrontFace front;
    VkPolygonMode polygon;
    VkBool32 depth_clamp, bias_enable, discard;
    float bias[3]; /* constant, clamp, slope */
    const VkDynamicState *dynamic;
    uint32_t dynamic_count;
    uint32_t view_mask;
    const void *next; /* chained after VkPipelineRenderingCreateInfo */
    VkBool32 sample_shading, alpha_to_coverage, alpha_to_one;
    float min_sample_shading;
    const VkSampleMask *sample_mask;
    uint32_t viewports; /* 0: one covering W x H */
    VkViewport viewport[2];
    VkRect2D scissor[2];
    VkPipelineCache cache;
    VkPipelineCreateFlags flags;
};

static void pipe_init(struct pipe *p, const uint32_t *vs, size_t vs_size, const uint32_t *fs, size_t fs_size)
{
    memset(p, 0, sizeof(*p));
    p->vs = vs;
    p->vs_size = vs_size;
    p->fs = fs;
    p->fs_size = fs_size;
    p->layout = pc_layout;
    p->topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_STRIP;
    p->colors = 1;
    p->color_formats[0] = VK_FORMAT_R8G8B8A8_UNORM;
    p->samples = VK_SAMPLE_COUNT_1_BIT;
    p->front = VK_FRONT_FACE_COUNTER_CLOCKWISE;
}

static VkResult make_pipe_result(const struct pipe *p, VkPipeline *out)
{
    VkGraphicsPipelineCreateInfo info;
    VkPipelineShaderStageCreateInfo stages[2];
    VkPipelineVertexInputStateCreateInfo vi;
    VkPipelineInputAssemblyStateCreateInfo ia;
    VkPipelineViewportStateCreateInfo vp;
    VkPipelineRasterizationStateCreateInfo rs;
    VkPipelineMultisampleStateCreateInfo ms;
    VkPipelineColorBlendStateCreateInfo cb;
    VkPipelineColorBlendAttachmentState att[4];
    VkPipelineDynamicStateCreateInfo dyn;
    VkPipelineRenderingCreateInfo rendering;
    VkViewport viewport;
    VkRect2D scissor;
    VkShaderModule vs = shader(p->vs, p->vs_size), fs = p->fs ? shader(p->fs, p->fs_size) : VK_NULL_HANDLE;
    VkPipelineDepthStencilStateCreateInfo ds;
    VkResult r;
    uint32_t i;

    memset(stages, 0, sizeof(stages));
    stages[0].sType = stages[1].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT;
    stages[0].module = vs;
    stages[0].pName = "main";
    stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
    stages[1].module = fs;
    stages[1].pName = "main";
    memset(&vi, 0, sizeof(vi));
    vi.sType = VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO;
    memset(&ia, 0, sizeof(ia));
    ia.sType = VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO;
    ia.topology = p->topology;
    ia.primitiveRestartEnable = p->restart;
    viewport.x = viewport.y = 0.0f;
    viewport.width = W;
    viewport.height = H;
    viewport.minDepth = 0.0f;
    viewport.maxDepth = 1.0f;
    scissor.offset.x = scissor.offset.y = 0;
    scissor.extent.width = W;
    scissor.extent.height = H;
    memset(&vp, 0, sizeof(vp));
    vp.sType = VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO;
    vp.viewportCount = vp.scissorCount = p->viewports ? p->viewports : 1;
    vp.pViewports = p->viewports ? p->viewport : &viewport;
    vp.pScissors = p->viewports ? p->scissor : &scissor;
    memset(&rs, 0, sizeof(rs));
    rs.sType = VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO;
    rs.polygonMode = p->polygon;
    rs.cullMode = p->cull;
    rs.frontFace = p->front;
    rs.depthClampEnable = p->depth_clamp;
    rs.rasterizerDiscardEnable = p->discard;
    rs.depthBiasEnable = p->bias_enable;
    rs.depthBiasConstantFactor = p->bias[0];
    rs.depthBiasClamp = p->bias[1];
    rs.depthBiasSlopeFactor = p->bias[2];
    rs.lineWidth = 1.0f;
    memset(&ms, 0, sizeof(ms));
    ms.sType = VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO;
    ms.rasterizationSamples = p->samples;
    ms.sampleShadingEnable = p->sample_shading;
    ms.minSampleShading = p->min_sample_shading;
    ms.pSampleMask = p->sample_mask;
    ms.alphaToCoverageEnable = p->alpha_to_coverage;
    ms.alphaToOneEnable = p->alpha_to_one;
    memset(att, 0, sizeof(att));
    for (i = 0; i < 4; i++)
        att[i].colorWriteMask = 0xf;
    memset(&cb, 0, sizeof(cb));
    cb.sType = VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO;
    cb.attachmentCount = p->colors;
    cb.pAttachments = p->has_blend ? p->blend : att;
    memcpy(cb.blendConstants, p->blend_constants, sizeof(cb.blendConstants));
    memset(&ds, 0, sizeof(ds));
    ds.sType = VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO;
    if (p->has_ds) {
        ds = p->ds;
        ds.sType = VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO;
    }
    memset(&dyn, 0, sizeof(dyn));
    dyn.sType = VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO;
    dyn.dynamicStateCount = p->dynamic_count;
    dyn.pDynamicStates = p->dynamic;
    memset(&rendering, 0, sizeof(rendering));
    rendering.sType = VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO;
    rendering.pNext = p->next;
    rendering.colorAttachmentCount = p->colors;
    rendering.pColorAttachmentFormats = p->color_formats;
    rendering.depthAttachmentFormat = p->depth_format;
    rendering.stencilAttachmentFormat = p->stencil_format;
    rendering.viewMask = p->view_mask;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO;
    info.pNext = p->rp ? NULL : &rendering;
    info.flags = p->flags;
    info.stageCount = p->fs ? 2 : 1;
    info.pStages = stages;
    info.pVertexInputState = p->vertex ? p->vertex : &vi;
    info.pInputAssemblyState = &ia;
    info.pViewportState = &vp;
    info.pRasterizationState = &rs;
    info.pMultisampleState = &ms;
    info.pDepthStencilState = &ds;
    info.pColorBlendState = &cb;
    info.pDynamicState = &dyn;
    info.layout = p->layout;
    info.renderPass = p->rp;
    info.subpass = p->subpass;
    *out = VK_NULL_HANDLE;
    r = vkCreateGraphicsPipelines(device, p->cache, 1, &info, NULL, out);
    vkDestroyShaderModule(device, vs, NULL);
    vkDestroyShaderModule(device, fs, NULL);
    return r;
}

static VkPipeline make_pipe(const struct pipe *p)
{
    VkPipeline pipeline;
    CHECK_VK(make_pipe_result(p, &pipeline), VK_SUCCESS);
    return pipeline;
}

