struct buf {
    VkBuffer buffer;
    VkDeviceMemory memory;
    unsigned char *data;
    VkDeviceSize size;
};

static struct buf make_buf(VkDeviceSize size)
{
    VkBufferCreateInfo info;
    VkMemoryAllocateInfo alloc;
    VkMemoryRequirements req;
    struct buf b;
    void *p = NULL;

    memset(&b, 0, sizeof(b));
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
    info.size = size;
    info.usage = VK_BUFFER_USAGE_VERTEX_BUFFER_BIT | VK_BUFFER_USAGE_INDEX_BUFFER_BIT |
                 VK_BUFFER_USAGE_INDIRECT_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_SRC_BIT |
                 VK_BUFFER_USAGE_TRANSFER_DST_BIT | VK_BUFFER_USAGE_STORAGE_BUFFER_BIT;
    if (vkCreateBuffer(device, &info, NULL, &b.buffer) != VK_SUCCESS)
        return b;
    vkGetBufferMemoryRequirements(device, b.buffer, &req);
    memset(&alloc, 0, sizeof(alloc));
    alloc.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    alloc.allocationSize = req.size;
    alloc.memoryTypeIndex = host_type;
    if (vkAllocateMemory(device, &alloc, NULL, &b.memory) != VK_SUCCESS)
        return b;
    vkBindBufferMemory(device, b.buffer, b.memory, 0);
    if (vkMapMemory(device, b.memory, 0, VK_WHOLE_SIZE, 0, &p) == VK_SUCCESS) {
        b.data = p;
        memset(b.data, 0, (size_t)size);
    }
    b.size = size;
    return b;
}

static void free_buf(struct buf *b)
{
    vkDestroyBuffer(device, b->buffer, NULL);
    vkFreeMemory(device, b->memory, NULL);
}

struct img {
    VkImage image;
    VkDeviceMemory memory;
    VkImageView view;
    VkFormat format;
    VkImageAspectFlags aspects;
    uint32_t w, h, layers;
};

static VkImageAspectFlags aspects_of(VkFormat f)
{
    switch (f) {
    case VK_FORMAT_D16_UNORM:
    case VK_FORMAT_D32_SFLOAT:
        return VK_IMAGE_ASPECT_DEPTH_BIT;
    case VK_FORMAT_S8_UINT:
        return VK_IMAGE_ASPECT_STENCIL_BIT;
    case VK_FORMAT_D32_SFLOAT_S8_UINT:
        return VK_IMAGE_ASPECT_DEPTH_BIT | VK_IMAGE_ASPECT_STENCIL_BIT;
    default:
        return VK_IMAGE_ASPECT_COLOR_BIT;
    }
}

/* An image with a view of all its layers (2D, or 2D array with layers > 1). */
static struct img make_img_mem(VkFormat format, uint32_t w, uint32_t h, uint32_t layers, VkSampleCountFlagBits samples,
                               VkImageUsageFlags usage, uint32_t type)
{
    VkImageCreateInfo info;
    VkImageViewCreateInfo view;
    VkMemoryAllocateInfo alloc;
    VkMemoryRequirements req;
    struct img m;

    memset(&m, 0, sizeof(m));
    m.format = format;
    m.aspects = aspects_of(format);
    m.w = w;
    m.h = h;
    m.layers = layers;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
    info.imageType = VK_IMAGE_TYPE_2D;
    info.format = format;
    info.extent.width = w;
    info.extent.height = h;
    info.extent.depth = 1;
    info.mipLevels = 1;
    info.arrayLayers = layers;
    info.samples = samples;
    info.tiling = VK_IMAGE_TILING_OPTIMAL;
    info.usage = usage;
    if (vkCreateImage(device, &info, NULL, &m.image) != VK_SUCCESS)
        return m;
    vkGetImageMemoryRequirements(device, m.image, &req);
    memset(&alloc, 0, sizeof(alloc));
    alloc.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    alloc.allocationSize = req.size;
    alloc.memoryTypeIndex = type;
    if (vkAllocateMemory(device, &alloc, NULL, &m.memory) != VK_SUCCESS)
        return m;
    vkBindImageMemory(device, m.image, m.memory, 0);
    memset(&view, 0, sizeof(view));
    view.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
    view.image = m.image;
    view.viewType = layers > 1 ? VK_IMAGE_VIEW_TYPE_2D_ARRAY : VK_IMAGE_VIEW_TYPE_2D;
    view.format = format;
    view.subresourceRange.aspectMask = m.aspects;
    view.subresourceRange.levelCount = 1;
    view.subresourceRange.layerCount = layers;
    vkCreateImageView(device, &view, NULL, &m.view);
    return m;
}

#define ATTACHMENT_USAGE                                                                                           \
    (VK_IMAGE_USAGE_TRANSFER_SRC_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_INPUT_ATTACHMENT_BIT |    \
     VK_IMAGE_USAGE_SAMPLED_BIT)

static struct img make_img(VkFormat format, uint32_t w, uint32_t h, uint32_t layers, VkSampleCountFlagBits samples)
{
    VkImageUsageFlags usage = ATTACHMENT_USAGE | (aspects_of(format) & VK_IMAGE_ASPECT_COLOR_BIT
                                                      ? VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT
                                                      : VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT);
    return make_img_mem(format, w, h, layers, samples, usage, device_type);
}

static void free_img(struct img *m)
{
    vkDestroyImageView(device, m->view, NULL);
    vkDestroyImage(device, m->image, NULL);
    vkFreeMemory(device, m->memory, NULL);
}

