/* Dynamic rendering into color images (load op CLEAR with `clear`, or LOAD
 * when clear is NULL), with an optional depth/stencil image cleared to
 * depth 1, stencil 0. */
static void begin_rendering(VkCommandBuffer cb, const struct img *colors, uint32_t n, const float *clear,
                            const struct img *ds)
{
    VkRenderingAttachmentInfo att[4], dsa;
    VkRenderingInfo info;
    uint32_t i;
    memset(att, 0, sizeof(att));
    for (i = 0; i < n; i++) {
        att[i].sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO;
        att[i].imageView = colors[i].view;
        att[i].imageLayout = VK_IMAGE_LAYOUT_GENERAL;
        att[i].loadOp = clear ? VK_ATTACHMENT_LOAD_OP_CLEAR : VK_ATTACHMENT_LOAD_OP_LOAD;
        att[i].storeOp = VK_ATTACHMENT_STORE_OP_STORE;
        if (clear)
            memcpy(att[i].clearValue.color.float32, clear, 16);
    }
    memset(&dsa, 0, sizeof(dsa));
    if (ds) {
        dsa.sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO;
        dsa.imageView = ds->view;
        dsa.imageLayout = VK_IMAGE_LAYOUT_GENERAL;
        dsa.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
        dsa.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
        dsa.clearValue.depthStencil.depth = 1.0f;
    }
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_RENDERING_INFO;
    info.renderArea.extent.width = colors ? colors[0].w : ds->w;
    info.renderArea.extent.height = colors ? colors[0].h : ds->h;
    info.layerCount = 1;
    info.colorAttachmentCount = n;
    info.pColorAttachments = att;
    info.pDepthAttachment = ds && (ds->aspects & VK_IMAGE_ASPECT_DEPTH_BIT) ? &dsa : NULL;
    info.pStencilAttachment = ds && (ds->aspects & VK_IMAGE_ASPECT_STENCIL_BIT) ? &dsa : NULL;
    vkCmdBeginRendering(cb, &info);
}

/* Draws spv_rect_vs's rectangle (x0, y0, x1, y1 in NDC) with a color. */
static void rect(VkCommandBuffer cb, float x0, float y0, float x1, float y1, float r, float g, float b, float a,
                 float depth)
{
    struct pc pc;
    memset(&pc, 0, sizeof(pc));
    pc.rect[0] = x0;
    pc.rect[1] = y0;
    pc.rect[2] = x1;
    pc.rect[3] = y1;
    pc.color[0] = r;
    pc.color[1] = g;
    pc.color[2] = b;
    pc.color[3] = a;
    pc.depth = depth;
    vkCmdPushConstants(cb, pc_layout, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(pc), &pc);
    vkCmdDraw(cb, 4, 1, 0, 0);
}

/* RGBA8 pixel (x, y) of a tightly packed W-wide download. */
static uint32_t px(const struct buf *b, uint32_t x, uint32_t y)
{
    uint32_t v;
    memcpy(&v, b->data + 4 * (y * W + x), 4);
    return v;
}

#define RGBA(r, g, b, a) ((uint32_t)(r) | ((uint32_t)(g) << 8) | ((uint32_t)(b) << 16) | ((uint32_t)(a) << 24))

/* Counts pixels of a W x H RGBA8 download that differ from expect(x, y). */
static int count_bad(const struct buf *b, uint32_t (*expect)(uint32_t x, uint32_t y), const char *what)
{
    uint32_t x, y;
    int bad = 0;
    for (y = 0; y < H; y++)
        for (x = 0; x < W; x++) {
            uint32_t got = px(b, x, y), want = expect(x, y);
            if (got != want) {
                if (bad < 4)
                    fprintf(stderr, "%s: pixel (%u, %u) is %08x, expected %08x\n", what, x, y, got, want);
                bad++;
            }
        }
    return bad;
}

