#define RED RGBA(255, 0, 0, 255)
#define GREEN RGBA(0, 255, 0, 255)
#define BLUE RGBA(0, 0, 255, 255)
#define BLACK RGBA(0, 0, 0, 255)
#define WHITE RGBA(255, 255, 255, 255)

static uint32_t expect_halves(uint32_t x, uint32_t y)
{
    if (x < W / 2)
        return RED;
    return y < H / 2 ? GREEN : BLACK;
}

/* A clear, then rectangles: NDC x -1 is the left edge and y -1 the top. */
static void test_dynamic_rendering(void)
{
    static const float black[4] = { 0, 0, 0, 1 };
    struct img target = make_img(VK_FORMAT_R8G8B8A8_UNORM, W, H, 1, VK_SAMPLE_COUNT_1_BIT);
    struct buf out = make_buf(W * H * 4);
    struct pipe p;
    VkPipeline pipeline;
    VkCommandBuffer cb;

    pipe_init(&p, spv_rect_vs, sizeof(spv_rect_vs), spv_rect_fs, sizeof(spv_rect_fs));
    pipeline = make_pipe(&p);
    REQUIRE(pipeline);
    cb = begin_cmd();
    begin_rendering(cb, &target, 1, black, NULL);
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline);
    rect(cb, -1, -1, 0, 1, 1, 0, 0, 1, 0);
    rect(cb, 0, -1, 1, 0, 0, 1, 0, 1, 0);
    vkCmdEndRendering(cb);
    download(cb, &target, 0, VK_IMAGE_ASPECT_COLOR_BIT, &out);
    submit(cb);
    CHECK(count_bad(&out, expect_halves, "dynamic rendering") == 0);
    vkDestroyPipeline(device, pipeline, NULL);
    free_buf(&out);
    free_img(&target);
}

static VkRenderPass make_simple_pass(VkFormat format, VkAttachmentLoadOp load, VkAttachmentStoreOp store)
{
    VkAttachmentDescription a;
    VkAttachmentReference ref;
    VkSubpassDescription sp;
    VkRenderPassCreateInfo info;
    VkRenderPass rp = VK_NULL_HANDLE;
    memset(&a, 0, sizeof(a));
    a.format = format;
    a.samples = VK_SAMPLE_COUNT_1_BIT;
    a.loadOp = load;
    a.storeOp = store;
    a.stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
    a.stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
    a.initialLayout = VK_IMAGE_LAYOUT_GENERAL;
    a.finalLayout = VK_IMAGE_LAYOUT_GENERAL;
    ref.attachment = 0;
    ref.layout = VK_IMAGE_LAYOUT_GENERAL;
    memset(&sp, 0, sizeof(sp));
    sp.pipelineBindPoint = VK_PIPELINE_BIND_POINT_GRAPHICS;
    sp.colorAttachmentCount = 1;
    sp.pColorAttachments = &ref;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_RENDER_PASS_CREATE_INFO;
    info.attachmentCount = 1;
    info.pAttachments = &a;
    info.subpassCount = 1;
    info.pSubpasses = &sp;
    vkCreateRenderPass(device, &info, NULL, &rp);
    return rp;
}

static VkFramebuffer make_fb(VkRenderPass rp, const VkImageView *views, uint32_t n, uint32_t w, uint32_t h,
                             uint32_t layers)
{
    VkFramebufferCreateInfo info;
    VkFramebuffer fb = VK_NULL_HANDLE;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO;
    info.renderPass = rp;
    info.attachmentCount = n;
    info.pAttachments = views;
    info.width = w;
    info.height = h;
    info.layers = layers;
    vkCreateFramebuffer(device, &info, NULL, &fb);
    return fb;
}

static void begin_pass(VkCommandBuffer cb, VkRenderPass rp, VkFramebuffer fb, int32_t x, int32_t y, uint32_t w,
                       uint32_t h, const VkClearValue *clears, uint32_t nclears)
{
    VkRenderPassBeginInfo info;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO;
    info.renderPass = rp;
    info.framebuffer = fb;
    info.renderArea.offset.x = x;
    info.renderArea.offset.y = y;
    info.renderArea.extent.width = w;
    info.renderArea.extent.height = h;
    info.clearValueCount = nclears;
    info.pClearValues = clears;
    vkCmdBeginRenderPass(cb, &info, VK_SUBPASS_CONTENTS_INLINE);
}

static uint32_t expect_ops(uint32_t x, uint32_t y)
{
    if (x >= 12 && y >= 4 && y < 12)
        return WHITE; /* the last pass's clear, in its render area only */
    if (y < H / 2)
        return GREEN;
    return x < W / 2 ? RED : BLUE;
}

/* Load op CLEAR, store, LOAD in a second instance, and a CLEAR limited to a
 * render area smaller than the attachment. */
static void test_render_pass_ops(void)
{
    struct img target = make_img(VK_FORMAT_R8G8B8A8_UNORM, W, H, 1, VK_SAMPLE_COUNT_1_BIT);
    struct buf out = make_buf(W * H * 4);
    VkRenderPass clear_rp = make_simple_pass(VK_FORMAT_R8G8B8A8_UNORM, VK_ATTACHMENT_LOAD_OP_CLEAR,
                                             VK_ATTACHMENT_STORE_OP_STORE);
    VkRenderPass load_rp = make_simple_pass(VK_FORMAT_R8G8B8A8_UNORM, VK_ATTACHMENT_LOAD_OP_LOAD,
                                            VK_ATTACHMENT_STORE_OP_STORE);
    VkFramebuffer fb = make_fb(clear_rp, &target.view, 1, W, H, 1);
    VkClearValue blue, white;
    struct pipe p;
    VkPipeline pipeline;
    VkCommandBuffer cb;

    memset(&blue, 0, sizeof(blue));
    blue.color.float32[2] = blue.color.float32[3] = 1.0f;
    memset(&white, 0, sizeof(white));
    white.color.float32[0] = white.color.float32[1] = white.color.float32[2] = white.color.float32[3] = 1.0f;
    pipe_init(&p, spv_rect_vs, sizeof(spv_rect_vs), spv_rect_fs, sizeof(spv_rect_fs));
    p.rp = clear_rp; /* compatible with load_rp */
    pipeline = make_pipe(&p);
    REQUIRE(pipeline);
    cb = begin_cmd();
    begin_pass(cb, clear_rp, fb, 0, 0, W, H, &blue, 1);
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline);
    rect(cb, -1, -1, 0, 1, 1, 0, 0, 1, 0);
    vkCmdEndRenderPass(cb);
    barrier(cb);
    begin_pass(cb, load_rp, fb, 0, 0, W, H, NULL, 0);
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline);
    rect(cb, -1, -1, 1, 0, 0, 1, 0, 1, 0);
    vkCmdEndRenderPass(cb);
    barrier(cb);
    begin_pass(cb, clear_rp, fb, 12, 4, 4, 8, &white, 1);
    vkCmdEndRenderPass(cb);
    download(cb, &target, 0, VK_IMAGE_ASPECT_COLOR_BIT, &out);
    submit(cb);
    CHECK(count_bad(&out, expect_ops, "render pass ops") == 0);
    vkDestroyPipeline(device, pipeline, NULL);
    vkDestroyFramebuffer(device, fb, NULL);
    vkDestroyRenderPass(device, clear_rp, NULL);
    vkDestroyRenderPass(device, load_rp, NULL);
    free_buf(&out);
    free_img(&target);
}

