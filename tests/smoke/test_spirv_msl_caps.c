/* Mismatches of one test: the first few are printed, the test then fails. */
static int bad;
#define EXPECT(cond, ...)                                       \
    do {                                                        \
        if (!(cond) && bad++ < 8) {                             \
            fprintf(stderr, "  mismatch: ");                    \
            fprintf(stderr, __VA_ARGS__);                       \
            fputc('\n', stderr);                                \
        }                                                       \
    } while (0)

static struct mt_binding bind(uint32_t set, uint32_t binding, struct mt_buffer *buf)
{
    struct mt_binding b;
    memset(&b, 0, sizeof(b));
    b.set = set;
    b.binding = binding;
    b.buf = buf;
    return b;
}

static uint32_t f2u(float f)
{
    uint32_t u;
    memcpy(&u, &f, 4);
    return u;
}

static float u2f(uint32_t u)
{
    float f;
    memcpy(&f, &u, 4);
    return f;
}

/* ==========================================================================
 * Subgroups
 *
 * Two SIMD-groups of 32 lanes per workgroup, each partially active: the
 * shaders branch on an input mask, so only the masked lanes take part.
 * Results from lanes Vulkan leaves undefined (reads of inactive lanes) are
 * not compared; inactive lanes must write nothing.
 * ========================================================================== */

static const uint32_t sg_masks[2] = { 0x5a5a5a5au, 0xfffff00fu };

struct sg_input {
    uint32_t mask[2];
    uint32_t d[2];
    int32_t vals[64];
};

static void sg_init(struct sg_input *in, uint32_t d0, uint32_t d1)
{
    uint32_t i;
    in->mask[0] = sg_masks[0];
    in->mask[1] = sg_masks[1];
    in->d[0] = d0;
    in->d[1] = d1;
    for (i = 0; i < 64; i++)
        in->vals[i] = (int32_t)((i * 7919u + 13u) % 2001u) - 1000;
}

static bool sg_active(uint32_t s, uint32_t lane)
{
    return lane < 32 && ((sg_masks[s] >> lane) & 1u);
}

static uint32_t popcount32(uint32_t v)
{
    uint32_t n = 0;
    for (; v; v &= v - 1)
        n++;
    return n;
}

/* Runs a one-workgroup subgroup test shader: input binding 0, output binding 1. */
static bool sg_run(const uint32_t *words, size_t count, const struct sg_input *in, uint32_t *out, size_t out_words)
{
    struct pvk_msl_result res;
    struct mt_buffer ib, ob;
    struct mt_binding b[2];
    id pso;
    bool ok;
    if (!mt_translate(words, count, NULL, &res))
        return false;
    pso = mt_pipeline(&res);
    if (!pso) {
        pvk_msl_result_free(&res);
        return false;
    }
    ib = mt_buffer(sizeof(*in), in, sizeof(*in));
    ob = mt_buffer(out_words * 4, NULL, 0);
    b[0] = bind(0, 0, &ib);
    b[1] = bind(0, 1, &ob);
    ok = mt_dispatch(pso, &res, b, 2, NULL, 0, 1, 1, 1);
    memcpy(out, ob.data, out_words * 4);
    mt_buffer_free(&ib);
    mt_buffer_free(&ob);
    pvk_release(pso);
    pvk_msl_result_free(&res);
    return ok;
}

static void check_sg_ballot(const uint32_t *words, size_t count)
{
    struct sg_input in;
    uint32_t out[64 * 32], s, l, k;
    sg_init(&in, 1, 0);
    REQUIRE(sg_run(words, count, &in, out, 64 * 32));
    bad = 0;
    for (s = 0; s < 2; s++) {
        uint32_t m = sg_masks[s], ball = 0, first = 32, all_pos = 1, all_ge = 1, any_big = 0, eq = 1, eq_sign = 1;
        int32_t v0 = 0;
        for (l = 0; l < 32; l++) {
            int32_t v = in.vals[32 * s + l];
            if (!sg_active(s, l))
                continue;
            if (first == 32) {
                first = l;
                v0 = v;
            }
            ball |= (v > 50 ? 1u : 0u) << l;
            all_pos &= v > 0;
            all_ge &= v > -1000;
            any_big |= v > 900;
            eq &= v == v0;
            eq_sign &= (v & 0x10000) == (v0 & 0x10000);
        }
        for (l = 0; l < 32; l++) {
            const uint32_t *o = out + (32 * s + l) * 32;
            int32_t v = in.vals[32 * s + l];
            uint32_t want[32];
            memset(want, 0, sizeof(want));
            want[0] = 32;
            want[1] = l;
            want[2] = s;
            want[3] = 2;
            want[4] = 1u << l;
            want[5] = 0xffffffffu << l;
            want[6] = 0xfffffffeu << l;
            want[7] = (uint32_t)((2ull << l) - 1);
            want[8] = (1u << l) - 1;
            if (sg_active(s, l)) {
                want[9] = l == first;
                want[10] = all_ge;
                want[11] = all_pos;
                want[12] = any_big;
                want[13] = eq;
                want[14] = eq_sign;
                want[15] = ball;
                want[16] = 0;
                want[17] = popcount32(ball);
                want[18] = popcount32(ball & (uint32_t)((2ull << l) - 1));
                want[19] = popcount32(ball & ((1u << l) - 1));
                for (k = 0; k < 32 && !((ball >> k) & 1u); k++)
                    ;
                want[20] = k;
                for (k = 31; k > 0 && !((ball >> k) & 1u); k--)
                    ;
                want[21] = k;
                want[22] = (ball >> l) & 1u;
                want[23] = (ball >> 9) & 1u;
                want[24] = (ball >> (l ^ 1)) & 1u;
                want[25] = (uint32_t)v0;
                want[26] = (uint32_t)in.vals[32 * s + 3];
                want[27] = (uint32_t)in.vals[32 * s + 1];
                want[28] = v0 > 0;
                want[30] = m;
                want[31] = 7;
                {
                    uint32_t j, pos = 0, neg = 0;
                    for (j = 0; j < 32; j++)
                        if (sg_active(s, j)) {
                            pos |= in.vals[32 * s + j] > 0;
                            neg |= in.vals[32 * s + j] <= 0;
                        }
                    want[29] = !(pos && neg);
                }
            }
            (void)v;
            for (k = 0; k < 32; k++)
                EXPECT(o[k] == want[k], "subgroup %u lane %u result %u: %u (0x%x), want %u (0x%x)", s, l, k, o[k], o[k],
                       want[k], want[k]);
        }
    }
    CHECK(bad == 0);
}

static void test_subgroup_ballot(void)
{
    check_sg_ballot(spv_sg_ballot, PVK_ARRAY_SIZE(spv_sg_ballot));
}

