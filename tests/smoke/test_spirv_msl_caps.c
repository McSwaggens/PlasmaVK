{
    check_sg_ballot(spv_sg_ballot_opt, PVK_ARRAY_SIZE(spv_sg_ballot_opt));
}

static void check_sg_shuffle(const uint32_t *words, size_t count)
{
    struct sg_input in;
    uint32_t out[64 * 16], s, l, k;
    sg_init(&in, 6, 2);
    REQUIRE(sg_run(words, count, &in, out, 64 * 16));
    bad = 0;
    for (s = 0; s < 2; s++) {
        for (l = 0; l < 32; l++) {
            const uint32_t *o = out + (32 * s + l) * 16;
            int src[16];
            if (!sg_active(s, l)) {
                for (k = 0; k < 16; k++)
                    EXPECT(o[k] == 0, "inactive lane %u of subgroup %u wrote result %u", l, s, k);
                continue;
            }
            src[0] = (int)((l * 5 + 3) & 31);
            src[1] = (int)(l ^ 1);
            src[2] = (int)(l ^ 6);
            src[3] = (int)l - 2;
            src[4] = (int)l - 2;
            src[5] = (int)l + 3;
            src[6] = (int)l + 2;
            src[7] = (int)((l + 5) & 31);
            src[8] = (int)((l & ~3u) | ((l + 1) & 3));
            src[9] = (int)((l & ~7u) | ((l + 2) & 7));
            src[10] = (int)(l ^ 1);
            src[11] = (int)(l ^ 2);
            src[12] = (int)(l ^ 3);
            src[13] = (int)((l & ~3u) | 2);
            src[14] = (int)(l ^ 2);
            src[15] = (int)(l ^ 4);
            for (k = 0; k < 16; k++) {
                int32_t sv;
                uint32_t want;
                if (src[k] < 0 || !sg_active(s, (uint32_t)src[k]))
                    continue; /* undefined in Vulkan */
                sv = in.vals[32 * s + (uint32_t)src[k]];
                want = k == 14 ? (uint32_t)(-sv) : k == 15 ? (uint32_t)(sv > 0) : (uint32_t)sv;
                EXPECT(o[k] == want, "subgroup %u lane %u result %u: %d, want %d (lane %d)", s, l, k, (int)o[k], (int)want,
                       src[k]);
            }
        }
    }
    CHECK(bad == 0);
}

