/* The active lanes before (exclusive), up to (inclusive) or all of lane l. */
enum { SG_REDUCE, SG_INCL, SG_EXCL };
static bool sg_in_range(uint32_t s, uint32_t j, uint32_t l, int mode)
{
    return sg_active(s, j) && (mode == SG_REDUCE || (mode == SG_INCL ? j <= l : j < l));
}

static void check_sg_arith(const uint32_t *words, size_t count)
{
    struct sg_input in;
    uint32_t out[64 * 48], s, l, k, j;
    int mode;
    sg_init(&in, 0, 0);
    REQUIRE(sg_run(words, count, &in, out, 64 * 48));
    bad = 0;
    for (s = 0; s < 2; s++) {
        for (l = 0; l < 32; l++) {
            const uint32_t *o = out + (32 * s + l) * 48;
            uint32_t want[48];
            if (!sg_active(s, l)) {
                for (k = 0; k < 48; k++)
                    EXPECT(o[k] == 0, "inactive lane %u of subgroup %u wrote result %u", l, s, k);
                continue;
            }
            for (mode = 0; mode < 3; mode++) {
                int32_t smin = INT32_MAX, smax = INT32_MIN;
                uint32_t add = 0, mul = 1, umin = UINT32_MAX, umax = 0, and_ = UINT32_MAX, or_ = 0, xor_ = 0;
                float fadd = 0.0f, fmul = 1.0f, fmin_ = INFINITY, fmax_ = -INFINITY;
                bool land = true, lor = false, lxor = false;
                for (j = 0; j < 32; j++) {
                    int32_t v;
                    uint32_t u;
                    float f, g;
                    bool p;
                    if (!sg_in_range(s, j, l, mode))
                        continue;
                    v = in.vals[32 * s + j];
                    u = (uint32_t)v * 2654435761u;
                    f = (float)(abs(v) % 64);
                    g = (v & 1) ? 2.0f : ((v & 2) ? 0.5f : -1.0f);
                    p = (v & 4) != 0;
                    add += (uint32_t)v;
                    mul *= u;
                    smin = v < smin ? v : smin;
                    smax = v > smax ? v : smax;
                    umin = u < umin ? u : umin;
                    umax = u > umax ? u : umax;
                    and_ &= u;
                    or_ |= u;
                    xor_ ^= u;
                    fadd += f;
                    fmul *= g;
                    fmin_ = f < fmin_ ? f : fmin_;
                    fmax_ = f > fmax_ ? f : fmax_;
                    land = land && p;
                    lor = lor || p;
                    lxor = lxor != p;
                }
                want[0 + mode] = add;
                want[3 + mode] = mul;
                want[6 + mode] = (uint32_t)smin;
                want[9 + mode] = umin;
                want[12 + mode] = (uint32_t)smax;
                want[15 + mode] = umax;
                want[18 + mode] = and_;
                want[21 + mode] = or_;
                want[24 + mode] = xor_;
                want[27 + mode] = f2u(fadd);
                want[30 + mode] = f2u(fmul);
                want[33 + mode] = f2u(fmin_);
                want[36 + mode] = f2u(fmax_);
                want[39 + mode] = land;
                want[42 + mode] = lor;
                want[45 + mode] = lxor;
            }
            for (k = 0; k < 48; k++) /* (the first lane's exclusive float sum may be -0: also an identity of +) */
                EXPECT(o[k] == want[k] || (k == 29 && u2f(o[k]) == u2f(want[k])), "subgroup %u lane %u result %u: 0x%08x (%g), want 0x%08x (%g)", s, l, k, o[k],
                       (double)u2f(o[k]), want[k], (double)u2f(want[k]));
        }
    }
    CHECK(bad == 0);
}

