/* Uploads w x h x d 32-bit texels of a level/layer from b (at 0), then reads
 * them back into b at `back`. */
static void upload_download(VkImage image, struct buf *b, VkDeviceSize back, uint32_t level, uint32_t layer,
                            uint32_t w, uint32_t h, uint32_t d)
{
    VkCommandBuffer cb = begin();
    VkBufferImageCopy r;
    to_general(cb, image, VK_IMAGE_ASPECT_COLOR_BIT);
    copy_region(&r, 0, level, layer, 0, 0, 0, w, h, d);
    vkCmdCopyBufferToImage(cb, b->buffer, image, VK_IMAGE_LAYOUT_GENERAL, 1, &r);
    barrier(cb);
    r.bufferOffset = back;
    vkCmdCopyImageToBuffer(cb, image, VK_IMAGE_LAYOUT_GENERAL, b->buffer, 1, &r);
    barrier(cb);
    submit(cb);
}

static void download(VkImage image, struct buf *b, VkDeviceSize at, uint32_t level, uint32_t layer, uint32_t w,
                     uint32_t h, uint32_t d)
{
    VkCommandBuffer cb = begin();
    VkBufferImageCopy r;
    copy_region(&r, at, level, layer, 0, 0, 0, w, h, d);
    vkCmdCopyImageToBuffer(cb, image, VK_IMAGE_LAYOUT_GENERAL, b->buffer, 1, &r);
    barrier(cb);
    submit(cb);
}

static uint32_t pattern(uint32_t i, uint32_t seed)
{
    return (i * 2654435761u) ^ (seed * 0x9E3779B9u) ^ 0x01010101u; /* never 0 */
}

static int has_sparse(void)
{
    if (!supported.sparseBinding) {
        printf("(sparse resources not supported)\n");
        return 0;
    }
    return 1;
}

/* ---- Properties ---- */

static void test_sparse_properties(void)
{
    VkQueueFamilyProperties families[8];
    VkPhysicalDeviceProperties props;
    uint32_t count = 8, i, sparse_families = 0;

    if (!has_sparse())
        return;
    CHECK(supported.sparseResidencyBuffer && supported.sparseResidencyImage2D && supported.sparseResidencyImage3D);
    CHECK(supported.sparseResidencyAliased && supported.sparseResidency2Samples && supported.sparseResidency4Samples);
    CHECK(!supported.sparseResidency8Samples && !supported.sparseResidency16Samples);
    CHECK(supported.shaderResourceResidency && supported.shaderResourceMinLod);
    vkGetPhysicalDeviceProperties(pd, &props);
    CHECK(props.limits.sparseAddressSpaceSize >= (1ull << 31));
    /* Measured (section 7): Metal's 64 KB tiles are the standard 2D shapes,
     * not the 3D and 2-sample ones; ALIGNED_MIP_SIZE; not strict (an
     * invocation reads back its own writes to unbound pages). */
    CHECK(sparse_props.residencyStandard2DBlockShape);
    CHECK(!sparse_props.residencyStandard2DMultisampleBlockShape);
    CHECK(!sparse_props.residencyStandard3DBlockShape);
    CHECK(sparse_props.residencyAlignedMipSize && !sparse_props.residencyNonResidentStrict);
    vkGetPhysicalDeviceQueueFamilyProperties(pd, &count, families);
    for (i = 0; i < count; i++)
        if (families[i].queueFlags & VK_QUEUE_SPARSE_BINDING_BIT)
            sparse_families++;
    CHECK(sparse_families == count);
}

static void test_sparse_format_properties(void)
{
    static const struct {
        VkFormat format;
        VkImageType type;
        VkSampleCountFlagBits samples;
        uint32_t w, h, d;
        VkSparseImageFormatFlags nonstandard;
    } cases[] = {
        { VK_FORMAT_R8_UNORM, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_1_BIT, 256, 256, 1, 0 },
        { VK_FORMAT_R16_SFLOAT, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_1_BIT, 256, 128, 1, 0 },
        { VK_FORMAT_R8G8B8A8_UNORM, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_1_BIT, 128, 128, 1, 0 },
        { VK_FORMAT_R16G16B16A16_SFLOAT, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_1_BIT, 128, 64, 1, 0 },
        { VK_FORMAT_R32G32B32A32_UINT, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_1_BIT, 64, 64, 1, 0 },
        { VK_FORMAT_ASTC_8x8_UNORM_BLOCK, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_1_BIT, 512, 512, 1, 0 },
        { VK_FORMAT_ETC2_R8G8B8_UNORM_BLOCK, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_1_BIT, 512, 256, 1, 0 },
        { VK_FORMAT_D32_SFLOAT, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_1_BIT, 128, 128, 1, 0 },
        { VK_FORMAT_R8G8B8A8_UNORM, VK_IMAGE_TYPE_3D, VK_SAMPLE_COUNT_1_BIT, 128, 128, 1,
          VK_SPARSE_IMAGE_FORMAT_NONSTANDARD_BLOCK_SIZE_BIT },
        { VK_FORMAT_R8G8B8A8_UNORM, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_4_BIT, 64, 64, 1, 0 },
        { VK_FORMAT_R8G8B8A8_UNORM, VK_IMAGE_TYPE_2D, VK_SAMPLE_COUNT_2_BIT, 128, 64, 1,
          VK_SPARSE_IMAGE_FORMAT_NONSTANDARD_BLOCK_SIZE_BIT },
    };
    VkSparseImageFormatProperties p[2];
    uint32_t i, count;

    if (!has_sparse())
        return;
    for (i = 0; i < PVK_ARRAY_SIZE(cases); i++) {
        VkImageUsageFlags usage = VK_IMAGE_USAGE_SAMPLED_BIT;
        if (cases[i].samples > 1)
            usage |= VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT;
        if (cases[i].format == VK_FORMAT_D32_SFLOAT)
            usage |= VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT;
        count = 2;
        memset(p, 0, sizeof(p));
        vkGetPhysicalDeviceSparseImageFormatProperties(pd, cases[i].format, cases[i].type, cases[i].samples, usage,
                                                       VK_IMAGE_TILING_OPTIMAL, &count, p);
        if (count != 1) {
            PVK_TEST_FAIL("case %u: %u properties", i, count);
            continue;
        }
        if (p[0].imageGranularity.width != cases[i].w || p[0].imageGranularity.height != cases[i].h ||
            p[0].imageGranularity.depth != cases[i].d ||
            (p[0].flags & VK_SPARSE_IMAGE_FORMAT_NONSTANDARD_BLOCK_SIZE_BIT) != cases[i].nonstandard ||
            !(p[0].flags & VK_SPARSE_IMAGE_FORMAT_ALIGNED_MIP_SIZE_BIT))
            PVK_TEST_FAIL("case %u: granularity %ux%ux%u flags 0x%x", i, p[0].imageGranularity.width,
                          p[0].imageGranularity.height, p[0].imageGranularity.depth, p[0].flags);
        CHECK(p[0].aspectMask == (cases[i].format == VK_FORMAT_D32_SFLOAT ? VK_IMAGE_ASPECT_DEPTH_BIT
                                                                            : VK_IMAGE_ASPECT_COLOR_BIT));
    }
    /* Not offered: combined depth/stencil (Metal drops the stencil), linear
     * tiling, 1D images. */
    count = 5;
    vkGetPhysicalDeviceSparseImageFormatProperties(pd, VK_FORMAT_D32_SFLOAT_S8_UINT, VK_IMAGE_TYPE_2D,
                                                   VK_SAMPLE_COUNT_1_BIT, VK_IMAGE_USAGE_SAMPLED_BIT,
                                                   VK_IMAGE_TILING_OPTIMAL, &count, p);
    CHECK(count == 0);
    count = 5;
    vkGetPhysicalDeviceSparseImageFormatProperties(pd, VK_FORMAT_R8G8B8A8_UNORM, VK_IMAGE_TYPE_1D,
                                                   VK_SAMPLE_COUNT_1_BIT, VK_IMAGE_USAGE_SAMPLED_BIT,
                                                   VK_IMAGE_TILING_OPTIMAL, &count, p);
    CHECK(count == 0);
}

