/* A 51x65 EAC R11 image with all its levels in the mip tail, level 0
 * sampled at each texel beside an ordinary image with the same blocks: its corner block is a
 * partial one (3x1 texels), which Metal's samplers read wrong from a sparse
 * texture's tail. */
static void test_sparse_compressed_tail(void)
{
    VkImageCreateInfo info = image_info(VK_IMAGE_TYPE_2D, VK_FORMAT_EAC_R11_UNORM_BLOCK, 51, 65, 1, 7, 1,
                                        VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT,
                                        VK_IMAGE_CREATE_SPARSE_BINDING_BIT | VK_IMAGE_CREATE_SPARSE_RESIDENCY_BIT);
    VkDescriptorSetLayoutBinding bindings[3];
    VkDescriptorSetLayoutCreateInfo set_layout_info;
    VkDescriptorPoolSize pool_sizes[2];
    VkDescriptorPoolCreateInfo pool_info;
    VkDescriptorSetAllocateInfo set_info;
    VkDescriptorImageInfo image_desc[2];
    VkDescriptorBufferInfo buffer_desc;
    VkWriteDescriptorSet writes[2];
    VkPipelineLayoutCreateInfo layout_info;
    VkSamplerCreateInfo sampler_info;
    VkSparseImageMemoryRequirements sr;
    VkMemoryRequirements req;
    VkDescriptorSetLayout set_layout;
    VkDescriptorPool desc_pool;
    VkDescriptorSet set;
    VkPipelineLayout layout;
    VkPipeline pipeline;
    VkSampler sampler;
    VkImage images[2];
    VkImageView views[2];
    VkDeviceMemory memory, plain_memory;
    VkCommandBuffer cb;
    VkBufferImageCopy copy;
    struct buf host, out;
    const float *f;
    uint32_t i, l, size = 2 * 13 * 17 * 8;
    VkDeviceSize at;
    VkFormatProperties fp;

    vkGetPhysicalDeviceFormatProperties(pd, VK_FORMAT_EAC_R11_UNORM_BLOCK, &fp);
    if (!has_sparse() || !(fp.optimalTilingFeatures & VK_FORMAT_FEATURE_SAMPLED_IMAGE_BIT))
        return;
    REQUIRE_VK(vkCreateImage(device, &info, NULL, &images[0]));
    sr = sparse_requirements(images[0]);
    CHECK(sr.imageMipTailFirstLod == 0);
    memory = allocate(private_type, sr.imageMipTailSize);
    REQUIRE(memory);
    bind_opaque(images[0], sr.imageMipTailOffset, sr.imageMipTailSize, memory, 0);
    info.flags = 0;
    REQUIRE_VK(vkCreateImage(device, &info, NULL, &images[1]));
    vkGetImageMemoryRequirements(device, images[1], &req);
    plain_memory = allocate(private_type, req.size);
    REQUIRE(plain_memory);
    REQUIRE_VK(vkBindImageMemory(device, images[1], plain_memory, 0));
    host = host_buf(size);
    out = host_buf(48);
    REQUIRE(host.data && out.data);
    for (i = 0; i < size; i++)
        ((uint8_t *)host.data)[i] = (uint8_t)pattern(i, 7);
    cb = begin();
    for (i = 0; i < 2; i++) {
        to_general(cb, images[i], VK_IMAGE_ASPECT_COLOR_BIT);
        for (l = 0, at = 0; l < 7; l++) { /* every level, as the CTS uploads them */
            uint32_t w = 51u >> l ? 51u >> l : 1u, h = 65u >> l ? 65u >> l : 1u;
            copy_region(&copy, at, l, 0, 0, 0, 0, w, h, 1);
            vkCmdCopyBufferToImage(cb, host.buffer, images[i], VK_IMAGE_LAYOUT_GENERAL, 1, &copy);
            at += (VkDeviceSize)((w + 3) / 4) * ((h + 3) / 4) * 8;
        }
    }
    barrier(cb);
    submit(cb);

    memset(&sampler_info, 0, sizeof(sampler_info));
    sampler_info.sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO;
    sampler_info.magFilter = sampler_info.minFilter = VK_FILTER_NEAREST;
    sampler_info.addressModeU = sampler_info.addressModeV = sampler_info.addressModeW =
        VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    REQUIRE_VK(vkCreateSampler(device, &sampler_info, NULL, &sampler));
    memset(bindings, 0, sizeof(bindings));
    for (i = 0; i < 3; i++) {
        bindings[i].binding = i;
        bindings[i].descriptorType = i < 2 ? VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER : VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        bindings[i].descriptorCount = 1;
        bindings[i].stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;
    }
    memset(&set_layout_info, 0, sizeof(set_layout_info));
    set_layout_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
    set_layout_info.bindingCount = 3;
    set_layout_info.pBindings = bindings;
    REQUIRE_VK(vkCreateDescriptorSetLayout(device, &set_layout_info, NULL, &set_layout));
    pool_sizes[0].type = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
    pool_sizes[0].descriptorCount = 2;
    pool_sizes[1].type = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    pool_sizes[1].descriptorCount = 1;
    memset(&pool_info, 0, sizeof(pool_info));
    pool_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
    pool_info.maxSets = 1;
    pool_info.poolSizeCount = 2;
    pool_info.pPoolSizes = pool_sizes;
    REQUIRE_VK(vkCreateDescriptorPool(device, &pool_info, NULL, &desc_pool));
    memset(&set_info, 0, sizeof(set_info));
    set_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
    set_info.descriptorPool = desc_pool;
    set_info.descriptorSetCount = 1;
    set_info.pSetLayouts = &set_layout;
    REQUIRE_VK(vkAllocateDescriptorSets(device, &set_info, &set));
    for (i = 0; i < 2; i++) {
        views[i] = make_view(images[i], VK_FORMAT_EAC_R11_UNORM_BLOCK, VK_IMAGE_ASPECT_COLOR_BIT);
        image_desc[i].sampler = sampler;
        image_desc[i].imageView = views[i];
        image_desc[i].imageLayout = VK_IMAGE_LAYOUT_GENERAL;
    }
    buffer_desc.buffer = out.buffer;
    buffer_desc.offset = 0;
    buffer_desc.range = VK_WHOLE_SIZE;
    memset(writes, 0, sizeof(writes));
    writes[0].sType = writes[1].sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
    writes[0].dstSet = writes[1].dstSet = set;
    writes[0].descriptorCount = 2;
    writes[0].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
    writes[0].pImageInfo = image_desc;
    writes[1].dstBinding = 2;
    writes[1].descriptorCount = 1;
    writes[1].descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    writes[1].pBufferInfo = &buffer_desc;
    vkUpdateDescriptorSets(device, 2, writes, 0, NULL);
    memset(&layout_info, 0, sizeof(layout_info));
    layout_info.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
    layout_info.setLayoutCount = 1;
    layout_info.pSetLayouts = &set_layout;
    REQUIRE_VK(vkCreatePipelineLayout(device, &layout_info, NULL, &layout));
    pipeline = compute_pipeline(spv_compressed_tail, sizeof(spv_compressed_tail), layout);
    REQUIRE(pipeline);

    cb = begin();
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_COMPUTE, pipeline);
    vkCmdBindDescriptorSets(cb, VK_PIPELINE_BIND_POINT_COMPUTE, layout, 0, 1, &set, 0, NULL);
    vkCmdDispatch(cb, 7, 9, 1);
    barrier(cb);
    submit(cb);
    f = (const float *)((const uint8_t *)out.data + 16);
    if (*(const uint32_t *)out.data)
        PVK_TEST_FAIL("%u texels differ, e.g. red %g, want %g", *(const uint32_t *)out.data, (double)f[0],
                      (double)f[4]);
    CHECK(*(const uint32_t *)out.data == 0);

    vkDestroyPipeline(device, pipeline, NULL);
    vkDestroyPipelineLayout(device, layout, NULL);
    vkDestroyDescriptorPool(device, desc_pool, NULL);
    vkDestroyDescriptorSetLayout(device, set_layout, NULL);
    for (i = 0; i < 2; i++) {
        vkDestroyImageView(device, views[i], NULL);
        vkDestroyImage(device, images[i], NULL);
    }
    vkDestroySampler(device, sampler, NULL);
    vkFreeMemory(device, memory, NULL);
    vkFreeMemory(device, plain_memory, NULL);
    free_buf(&host);
    free_buf(&out);
}

/* spv_storage_tail on level `level` (w x h) of an RGBA8_UINT storage image:
 * each texel's { resident, R, G, 7 } into out (w * h * 4 uints). */
static void storage_read(VkImage image, uint32_t level, uint32_t w, uint32_t h, uint32_t *out)
{
    VkDescriptorSetLayoutBinding binding;
    VkDescriptorSetLayoutCreateInfo set_layout_info;
    VkDescriptorPoolSize pool_size;
    VkDescriptorPoolCreateInfo pool_info;
    VkDescriptorSetAllocateInfo set_info;
    VkDescriptorImageInfo desc;
    VkWriteDescriptorSet write;
    VkPushConstantRange range;
    VkPipelineLayoutCreateInfo layout_info;
    VkImageViewCreateInfo view_info;
    VkDescriptorSetLayout set_layout;
    VkDescriptorPool desc_pool;
    VkDescriptorSet set;
    VkPipelineLayout layout;
    VkPipeline pipeline;
    VkImageView view;
    VkCommandBuffer cb;
    struct buf host = host_buf((VkDeviceSize)w * h * 16);
    struct {
        VkDeviceAddress dst;
        uint32_t w, h;
    } push;

    REQUIRE(host.data);
    memset(&view_info, 0, sizeof(view_info));
    view_info.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
    view_info.image = image;
    view_info.viewType = VK_IMAGE_VIEW_TYPE_2D;
    view_info.format = VK_FORMAT_R8G8B8A8_UINT;
    view_info.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
    view_info.subresourceRange.baseMipLevel = level;
    view_info.subresourceRange.levelCount = 1;
    view_info.subresourceRange.layerCount = 1;
    REQUIRE_VK(vkCreateImageView(device, &view_info, NULL, &view));
    memset(&binding, 0, sizeof(binding));
    binding.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_IMAGE;
    binding.descriptorCount = 1;
    binding.stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;
    memset(&set_layout_info, 0, sizeof(set_layout_info));
    set_layout_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
    set_layout_info.bindingCount = 1;
    set_layout_info.pBindings = &binding;
    REQUIRE_VK(vkCreateDescriptorSetLayout(device, &set_layout_info, NULL, &set_layout));
    pool_size.type = VK_DESCRIPTOR_TYPE_STORAGE_IMAGE;
    pool_size.descriptorCount = 1;
    memset(&pool_info, 0, sizeof(pool_info));
    pool_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
    pool_info.maxSets = 1;
    pool_info.poolSizeCount = 1;
    pool_info.pPoolSizes = &pool_size;
    REQUIRE_VK(vkCreateDescriptorPool(device, &pool_info, NULL, &desc_pool));
    memset(&set_info, 0, sizeof(set_info));
    set_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
    set_info.descriptorPool = desc_pool;
    set_info.descriptorSetCount = 1;
    set_info.pSetLayouts = &set_layout;
    REQUIRE_VK(vkAllocateDescriptorSets(device, &set_info, &set));
    desc.sampler = VK_NULL_HANDLE;
    desc.imageView = view;
    desc.imageLayout = VK_IMAGE_LAYOUT_GENERAL;
    memset(&write, 0, sizeof(write));
    write.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
    write.dstSet = set;
    write.descriptorCount = 1;
    write.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_IMAGE;
    write.pImageInfo = &desc;
    vkUpdateDescriptorSets(device, 1, &write, 0, NULL);
    memset(&range, 0, sizeof(range));
    range.stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;
    range.size = sizeof(push);
    memset(&layout_info, 0, sizeof(layout_info));
    layout_info.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
    layout_info.setLayoutCount = 1;
    layout_info.pSetLayouts = &set_layout;
    layout_info.pushConstantRangeCount = 1;
    layout_info.pPushConstantRanges = &range;
    REQUIRE_VK(vkCreatePipelineLayout(device, &layout_info, NULL, &layout));
    pipeline = compute_pipeline(spv_storage_tail, sizeof(spv_storage_tail), layout);
    REQUIRE(pipeline);

    memset(&push, 0, sizeof(push));
    push.dst = host.address;
    push.w = w;
    push.h = h;
    cb = begin();
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_COMPUTE, pipeline);
    vkCmdBindDescriptorSets(cb, VK_PIPELINE_BIND_POINT_COMPUTE, layout, 0, 1, &set, 0, NULL);
    vkCmdPushConstants(cb, layout, VK_SHADER_STAGE_COMPUTE_BIT, 0, sizeof(push), &push);
    vkCmdDispatch(cb, (w + 7) / 8, (h + 7) / 8, 1);
    barrier(cb);
    submit(cb);
    memcpy(out, host.data, (size_t)w * h * 16);

    vkDestroyPipeline(device, pipeline, NULL);
    vkDestroyPipelineLayout(device, layout, NULL);
    vkDestroyDescriptorPool(device, desc_pool, NULL);
    vkDestroyDescriptorSetLayout(device, set_layout, NULL);
    vkDestroyImageView(device, view, NULL);
    free_buf(&host);
}

/* Uploads pattern(i, seed) texels to level `level` (w x h) of an image. */
static void upload_level(VkImage image, uint32_t level, uint32_t w, uint32_t h, uint32_t seed)
{
    struct buf host = host_buf((VkDeviceSize)w * h * 4);
    uint32_t *words = (uint32_t *)host.data, i;
    VkCommandBuffer cb;
    VkBufferImageCopy copy;
    REQUIRE(words);
    for (i = 0; i < w * h; i++)
        words[i] = pattern(i, seed);
    cb = begin();
    to_general(cb, image, VK_IMAGE_ASPECT_COLOR_BIT);
    copy_region(&copy, 0, level, 0, 0, 0, 0, w, h, 1);
    vkCmdCopyBufferToImage(cb, host.buffer, image, VK_IMAGE_LAYOUT_GENERAL, 1, &copy);
    barrier(cb);
    submit(cb);
    free_buf(&host);
}

/* Whether out (storage_read) says each texel is `resident` and, if so, holds
 * pattern(i, seed); reports the first few that don't. */
static int storage_check(const uint32_t *out, uint32_t n, int resident, uint32_t seed, const char *what)
{
    uint32_t i, bad = 0;
    for (i = 0; i < n; i++) {
        const uint32_t *o = &out[i * 4], p = pattern(i, seed);
        int ok = o[0] == (uint32_t)resident && o[3] == 7 &&
                 (!resident || (o[1] == (p & 0xFF) && o[2] == ((p >> 8) & 0xFF)));
        if (!ok && bad++ < 4)
            PVK_TEST_FAIL("%s: texel %u: %u %u %u %u", what, i, o[0], o[1], o[2], o[3]);
    }
    return bad == 0;
}

/* Sparse loads of storage images (spv_storage_tail). Metal's residency
 * queries of ShaderWrite textures are wrong for levels smaller than a tile,
 * and a shader with a sparse read hangs the GPU reading one whose every
 * level is in the tail (section 7); sparse storage images answer through a
 * residency texture, and those entirely in the tail are ordinary textures:
 * - 11x37, every level in the tail: resident with its texels while the tail
 *   is bound, not resident once it is unbound;
 * - 256x256, level 2 (64x64, in the Vulkan tail; ShaderWrite puts it before
 *   Metal's tail) and level 4 (in Metal's tail): resident once the tail is
 *   bound, level 0 not;
 * - 64x64, level 0 smaller than a block but before ShaderWrite's Metal tail
 *   (a hang too): resident while the tail is bound;
 * - 11x37 without residency (sparse binding only), and not sparse: always
 *   resident. */
static void test_sparse_storage_reads(void)
{
    const VkImageUsageFlags usage = VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_STORAGE_BIT;
    const VkImageCreateFlags residency = VK_IMAGE_CREATE_SPARSE_BINDING_BIT | VK_IMAGE_CREATE_SPARSE_RESIDENCY_BIT;
    VkImageCreateInfo info;
    VkSparseImageMemoryRequirements sr;
    VkMemoryRequirements req;
    VkImage image;
    VkDeviceMemory memory;
    static uint32_t out[256 * 256 * 4];

    if (!has_sparse() || !supported.sparseResidencyImage2D || !supported.shaderResourceResidency)
        return;
    /* 11x37 */
    info = image_info(VK_IMAGE_TYPE_2D, VK_FORMAT_R8G8B8A8_UINT, 11, 37, 1, 6, 1, usage, residency);
    REQUIRE_VK(vkCreateImage(device, &info, NULL, &image));
    sr = sparse_requirements(image);
    CHECK(sr.imageMipTailFirstLod == 0);
    memory = allocate(private_type, sr.imageMipTailSize);
    REQUIRE(memory);
    bind_opaque(image, sr.imageMipTailOffset, sr.imageMipTailSize, memory, 0);
    upload_level(image, 0, 11, 37, 50);
    storage_read(image, 0, 11, 37, out);
    CHECK(storage_check(out, 11 * 37, 1, 50, "11x37 bound"));
    bind_opaque(image, sr.imageMipTailOffset, sr.imageMipTailSize, VK_NULL_HANDLE, 0);
    storage_read(image, 0, 11, 37, out);
    CHECK(storage_check(out, 11 * 37, 0, 50, "11x37 unbound"));
    vkDestroyImage(device, image, NULL);
    vkFreeMemory(device, memory, NULL);

    /* 256x256, levels 2 and 4 */
    info = image_info(VK_IMAGE_TYPE_2D, VK_FORMAT_R8G8B8A8_UINT, 256, 256, 1, 9, 1, usage, residency);
    REQUIRE_VK(vkCreateImage(device, &info, NULL, &image));
    sr = sparse_requirements(image);
    REQUIRE(sr.imageMipTailFirstLod == 2);
    memory = allocate(private_type, sr.imageMipTailSize);
    REQUIRE(memory);
    bind_opaque(image, sr.imageMipTailOffset, sr.imageMipTailSize, memory, 0);
    upload_level(image, 2, 64, 64, 51);
    storage_read(image, 2, 64, 64, out);
    CHECK(storage_check(out, 64 * 64, 1, 51, "256x256 level 2"));
    upload_level(image, 4, 16, 16, 54);
    storage_read(image, 4, 16, 16, out);
    CHECK(storage_check(out, 16 * 16, 1, 54, "256x256 level 4"));
    storage_read(image, 0, 256, 256, out);
    CHECK(storage_check(out, 256 * 256, 0, 0, "256x256 level 0 unbound"));
    vkDestroyImage(device, image, NULL);
    vkFreeMemory(device, memory, NULL);

    /* 64x64: level 0 is smaller than a block but before ShaderWrite's Metal tail */
    info = image_info(VK_IMAGE_TYPE_2D, VK_FORMAT_R8G8B8A8_UINT, 64, 64, 1, 7, 1, usage, residency);
    REQUIRE_VK(vkCreateImage(device, &info, NULL, &image));
    sr = sparse_requirements(image);
    REQUIRE(sr.imageMipTailFirstLod == 0);
    memory = allocate(private_type, sr.imageMipTailSize);
    REQUIRE(memory);
    bind_opaque(image, sr.imageMipTailOffset, sr.imageMipTailSize, memory, 0);
    upload_level(image, 0, 64, 64, 55);
    storage_read(image, 0, 64, 64, out);
    CHECK(storage_check(out, 64 * 64, 1, 55, "64x64 bound"));
    upload_level(image, 2, 16, 16, 56);
    storage_read(image, 2, 16, 16, out);
    CHECK(storage_check(out, 16 * 16, 1, 56, "64x64 level 2"));
    bind_opaque(image, sr.imageMipTailOffset, sr.imageMipTailSize, VK_NULL_HANDLE, 0);
    storage_read(image, 0, 64, 64, out);
    CHECK(storage_check(out, 64 * 64, 0, 55, "64x64 unbound"));
    vkDestroyImage(device, image, NULL);
    vkFreeMemory(device, memory, NULL);

    /* 11x37 without residency */
    info = image_info(VK_IMAGE_TYPE_2D, VK_FORMAT_R8G8B8A8_UINT, 11, 37, 1, 6, 1, usage,
                      VK_IMAGE_CREATE_SPARSE_BINDING_BIT);
    REQUIRE_VK(vkCreateImage(device, &info, NULL, &image));
    vkGetImageMemoryRequirements(device, image, &req);
    memory = allocate(private_type, req.size);
    REQUIRE(memory);
    bind_opaque(image, 0, req.size, memory, 0);
    upload_level(image, 0, 11, 37, 52);
    storage_read(image, 0, 11, 37, out);
    CHECK(storage_check(out, 11 * 37, 1, 52, "11x37 without residency"));
    vkDestroyImage(device, image, NULL);
    vkFreeMemory(device, memory, NULL);

    /* not sparse: the image answers for itself */
    info = image_info(VK_IMAGE_TYPE_2D, VK_FORMAT_R8G8B8A8_UINT, 11, 37, 1, 6, 1, usage, 0);
    REQUIRE_VK(vkCreateImage(device, &info, NULL, &image));
    vkGetImageMemoryRequirements(device, image, &req);
    memory = allocate(private_type, req.size);
    REQUIRE(memory);
    REQUIRE_VK(vkBindImageMemory(device, image, memory, 0));
    upload_level(image, 0, 11, 37, 53);
    storage_read(image, 0, 11, 37, out);
    CHECK(storage_check(out, 11 * 37, 1, 53, "11x37 not sparse"));
    vkDestroyImage(device, image, NULL);
    vkFreeMemory(device, memory, NULL);
}

