static void wait_fence(void)
{
    CHECK_VK(vkWaitForFences(device, 1, &fence, VK_TRUE, 10000000000ull), VK_SUCCESS);
    vkResetFences(device, 1, &fence);
}

static void submit(VkCommandBuffer cb)
{
    VkSubmitInfo info;
    vkEndCommandBuffer(cb);
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
    info.commandBufferCount = 1;
    info.pCommandBuffers = &cb;
    CHECK_VK(vkQueueSubmit(queue, 1, &info, fence), VK_SUCCESS);
    wait_fence();
    vkFreeCommandBuffers(device, pool, 1, &cb);
}

