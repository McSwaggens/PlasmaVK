/* A buffer of four blocks: blocks 1 and 2 bound to private and shared
 * memory, the others unbound (writes dropped, reads 0); then block 1
 * unbound (reads 0 at once) and rebound to other memory, and the shared
 * memory seen by the host. */
static void test_sparse_buffer(void)
{
    VkMemoryRequirements req;
    VkBuffer buffer;
    VkDeviceMemory priv, shared;
    VkCommandBuffer cb;
    VkBufferCopy copy;
    struct buf host;
    uint32_t *words, *shared_words, i, b;
    const uint32_t per_block = BLOCK / 4;

    if (!has_sparse())
        return;
    buffer = sparse_buffer(4 * BLOCK - 100, VK_BUFFER_CREATE_SPARSE_RESIDENCY_BIT, &req);
    REQUIRE(buffer);
    CHECK(req.alignment == BLOCK && req.size == 4 * BLOCK);
    CHECK((req.memoryTypeBits & (1u << private_type)) && (req.memoryTypeBits & (1u << shared_type)));
    priv = allocate(private_type, 4 * BLOCK);
    shared = allocate(shared_type, 2 * BLOCK);
    REQUIRE(priv && shared);
    shared_words = map(shared);
    REQUIRE(shared_words);
    memset(shared_words, 0xEE, 2 * BLOCK);
    host = host_buf(4 * BLOCK);
    REQUIRE(host.data);
    words = (uint32_t *)host.data;

    bind_buffer(buffer, BLOCK, BLOCK, priv, 2 * BLOCK);
    bind_buffer(buffer, 2 * BLOCK, BLOCK, shared, 0);
    for (i = 0; i < 4 * per_block; i++)
        words[i] = pattern(i, 1);
    cb = begin();
    memset(&copy, 0, sizeof(copy));
    copy.size = 4 * BLOCK - 100;
    vkCmdCopyBuffer(cb, host.buffer, buffer, 1, &copy);
    barrier(cb);
    vkCmdFillBuffer(cb, host.buffer, 0, VK_WHOLE_SIZE, 0x5A5A5A5A);
    barrier(cb);
    vkCmdCopyBuffer(cb, buffer, host.buffer, 1, &copy);
    barrier(cb);
    submit(cb);
    for (b = 0; b < 4; b++) {
        int ok = 1;
        for (i = b * per_block; i < (b + 1) * per_block && i < (4 * BLOCK - 100) / 4; i++)
            if (words[i] != (b == 1 || b == 2 ? pattern(i, 1) : 0u))
                ok = 0;
        if (!ok)
            PVK_TEST_FAIL("block %u: %08x %08x", b, words[b * per_block], words[b * per_block + 1]);
    }
    /* block 2's data is in the shared memory, block 0 and 3's writes went nowhere */
    CHECK(shared_words[0] == pattern(2 * per_block, 1) && shared_words[per_block - 1] == pattern(3 * per_block - 1, 1));
    CHECK(shared_words[per_block] == 0xEEEEEEEEu);

    /* Unbind block 1: reads 0 at once; bind it to shared block 1 (host data). */
    bind_buffer(buffer, BLOCK, BLOCK, VK_NULL_HANDLE, 0);
    cb = begin();
    copy.size = BLOCK;
    copy.srcOffset = copy.dstOffset = BLOCK;
    vkCmdCopyBuffer(cb, buffer, host.buffer, 1, &copy);
    barrier(cb);
    submit(cb);
    CHECK(words[per_block] == 0 && words[2 * per_block - 1] == 0);
    for (i = 0; i < per_block; i++)
        shared_words[per_block + i] = pattern(i, 7);
    bind_buffer(buffer, BLOCK, BLOCK, shared, BLOCK);
    cb = begin();
    vkCmdCopyBuffer(cb, buffer, host.buffer, 1, &copy);
    barrier(cb);
    submit(cb);
    CHECK(words[per_block] == pattern(0, 7) && words[2 * per_block - 1] == pattern(per_block - 1, 7));
    /* and back to the private block, whose data is still there */
    bind_buffer(buffer, BLOCK, BLOCK, priv, 2 * BLOCK);
    cb = begin();
    vkCmdCopyBuffer(cb, buffer, host.buffer, 1, &copy);
    barrier(cb);
    submit(cb);
    CHECK(words[per_block] == pattern(per_block, 1) && words[2 * per_block - 1] == pattern(2 * per_block - 1, 1));

    vkDestroyBuffer(device, buffer, NULL);
    vkFreeMemory(device, priv, NULL);
    vkFreeMemory(device, shared, NULL);
    free_buf(&host);
}

static VkPipeline compute_pipeline(const uint32_t *code, size_t size, VkPipelineLayout layout)
{
    VkShaderModuleCreateInfo module_info;
    VkComputePipelineCreateInfo info;
    VkShaderModule module = VK_NULL_HANDLE;
    VkPipeline pipeline = VK_NULL_HANDLE;
    memset(&module_info, 0, sizeof(module_info));
    module_info.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
    module_info.codeSize = size;
    module_info.pCode = code;
    if (vkCreateShaderModule(device, &module_info, NULL, &module) != VK_SUCCESS)
        return VK_NULL_HANDLE;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO;
    info.stage.sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    info.stage.stage = VK_SHADER_STAGE_COMPUTE_BIT;
    info.stage.module = module;
    info.stage.pName = "main";
    info.layout = layout;
    if (vkCreateComputePipelines(device, VK_NULL_HANDLE, 1, &info, NULL, &pipeline) != VK_SUCCESS)
        PVK_TEST_FAIL("vkCreateComputePipelines failed");
    vkDestroyShaderModule(device, module, NULL);
    return pipeline;
}

/* A compute shader reading and writing a partially bound buffer through
 * device addresses: unbound words read 0, writes to them are dropped. */
static void test_sparse_buffer_shader(void)
{
    struct {
        VkDeviceAddress src, dst;
        uint32_t count, mul, add;
    } push;
    VkPushConstantRange range;
    VkPipelineLayoutCreateInfo layout_info;
    VkPipelineLayout layout;
    VkPipeline pipeline;
    VkMemoryRequirements req;
    VkBufferDeviceAddressInfo address;
    VkBuffer buffer;
    VkDeviceMemory memory;
    VkCommandBuffer cb;
    VkBufferCopy copy;
    struct buf host;
    uint32_t *words, i, n = 2 * BLOCK / 4;

    if (!has_sparse())
        return;
    buffer = sparse_buffer(2 * BLOCK, VK_BUFFER_CREATE_SPARSE_RESIDENCY_BIT, &req);
    REQUIRE(buffer);
    memory = allocate(private_type, BLOCK);
    host = host_buf(4 * BLOCK);
    REQUIRE(memory && host.data);
    bind_buffer(buffer, BLOCK, BLOCK, memory, 0); /* the second block */
    words = (uint32_t *)host.data;
    for (i = 0; i < n; i++)
        words[i] = i;
    memset(&range, 0, sizeof(range));
    range.stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;
    range.size = sizeof(push);
    memset(&layout_info, 0, sizeof(layout_info));
    layout_info.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
    layout_info.pushConstantRangeCount = 1;
    layout_info.pPushConstantRanges = &range;
    REQUIRE_VK(vkCreatePipelineLayout(device, &layout_info, NULL, &layout));
    pipeline = compute_pipeline(spv_scale, sizeof(spv_scale), layout);
    REQUIRE(pipeline);
    memset(&address, 0, sizeof(address));
    address.sType = VK_STRUCTURE_TYPE_BUFFER_DEVICE_ADDRESS_INFO;
    address.buffer = buffer;

    cb = begin();
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_COMPUTE, pipeline);
    /* host words -> sparse buffer (x3 + 1), then sparse -> host at 2 blocks (x1 + 0) */
    push.src = host.address;
    push.dst = vkGetBufferDeviceAddress(device, &address);
    push.count = n;
    push.mul = 3;
    push.add = 1;
    vkCmdPushConstants(cb, layout, VK_SHADER_STAGE_COMPUTE_BIT, 0, sizeof(push), &push);
    vkCmdDispatch(cb, n / 64, 1, 1);
    barrier(cb);
    push.src = push.dst;
    push.dst = host.address + 2 * BLOCK;
    push.mul = 1;
    push.add = 0;
    vkCmdPushConstants(cb, layout, VK_SHADER_STAGE_COMPUTE_BIT, 0, sizeof(push), &push);
    vkCmdDispatch(cb, n / 64, 1, 1);
    barrier(cb);
    submit(cb);
    CHECK(words[n + 0] == 0 && words[n + n / 2 - 1] == 0);
    CHECK(words[n + n / 2] == 3 * (n / 2) + 1 && words[2 * n - 1] == 3 * (n - 1) + 1);
    /* the bound block also reads back through a copy */
    cb = begin();
    memset(&copy, 0, sizeof(copy));
    copy.srcOffset = BLOCK;
    copy.size = BLOCK;
    vkCmdCopyBuffer(cb, buffer, host.buffer, 1, &copy);
    barrier(cb);
    submit(cb);
    CHECK(words[0] == 3 * (n / 2) + 1);

    vkDestroyPipeline(device, pipeline, NULL);
    vkDestroyPipelineLayout(device, layout, NULL);
    vkDestroyBuffer(device, buffer, NULL);
    vkFreeMemory(device, memory, NULL);
    free_buf(&host);
}

