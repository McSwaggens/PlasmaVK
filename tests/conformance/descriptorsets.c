/* Words [first, first + n) of dst are (i + base) * mul + add. */
static void check_scaled(struct ct *t, const struct ct_buffer *dst, size_t first, uint32_t n, uint32_t base, uint32_t mul,
                         uint32_t add, const char *what)
{
    uint32_t i;
    for (i = 0; i < n; i++)
        if (word(dst, first + i) != (i + base) * mul + add) {
            ct_fail(t, __FILE__, __LINE__, "%s: element %u is %u, expected %u", what, i, word(dst, first + i),
                    (i + base) * mul + add);
            return;
        }
}

/* A multiple of both buffer offset alignments, at least 256 bytes. */
static VkDeviceSize offset_step(const struct dt *d)
{
    VkDeviceSize a = d->e.props.limits.minUniformBufferOffsetAlignment, s = d->e.props.limits.minStorageBufferOffsetAlignment;
    VkDeviceSize step = a > s ? a : s;
    return step < 256 ? 256 : step;
}

