#define IMAGE_COMMANDS                                                                                          \
    DISPATCH_COMMANDS " vkCmdPushConstants vkCreateImage vkDestroyImage vkGetImageMemoryRequirements "        \
                      "vkBindImageMemory vkCreateImageView vkDestroyImageView vkCreateBufferView "            \
                      "vkDestroyBufferView vkCreateSampler vkDestroySampler vkCmdCopyBufferToImage "           \
                      "vkCmdCopyImageToBuffer"

/* What spv_image_types reads: sampled images imgs[0..2] (4x4 R32_SFLOAT,
 * texel (x, y) = 100 k + 4 y + x), a combined one (500 + 4 y + x), a 4x4
 * R32_SFLOAT storage image (900 + 4 y + x, + 1000 after), 16-texel
 * R32_UINT uniform (7000 + i) and storage (i * 3 + 1 after) texel buffers. */
struct scene {
    struct ct_image imgs[3], comb, simg;
    VkImageView imgs_view[3], comb_view, simg_view;
    struct ct_buffer staging, utb, stb, out, readback;
    VkBufferView utb_view, stb_view;
    VkSampler sampler;
};

static VkImageView make_view(struct ct *t, struct dt *d, VkImage image)
{
    VkImageViewCreateInfo info;
    VkImageView view = VK_NULL_HANDLE;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
    info.image = image;
    info.viewType = VK_IMAGE_VIEW_TYPE_2D;
    info.format = VK_FORMAT_R32_SFLOAT;
    info.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
    info.subresourceRange.levelCount = 1;
    info.subresourceRange.layerCount = 1;
    CT_REQUIRE_VK(t, vkCreateImageView(d->e.device, &info, NULL, &view));
    return view;
}

static VkBufferView make_texel_view(struct ct *t, struct dt *d, const struct ct_buffer *b)
{
    VkBufferViewCreateInfo info;
    VkBufferView view = VK_NULL_HANDLE;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_BUFFER_VIEW_CREATE_INFO;
    info.buffer = b->buffer;
    info.format = VK_FORMAT_R32_UINT;
    info.range = VK_WHOLE_SIZE;
    CT_REQUIRE_VK(t, vkCreateBufferView(d->e.device, &info, NULL, &view));
    return view;
}

static void copy_region(VkCommandBuffer cb, VkBuffer buffer, VkImage image, VkDeviceSize offset, bool to_image)
{
    VkBufferImageCopy r;
    memset(&r, 0, sizeof(r));
    r.bufferOffset = offset;
    r.imageSubresource.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
    r.imageSubresource.layerCount = 1;
    r.imageExtent.width = 4;
    r.imageExtent.height = 4;
    r.imageExtent.depth = 1;
    if (to_image)
        vkCmdCopyBufferToImage(cb, buffer, image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &r);
    else
        vkCmdCopyImageToBuffer(cb, image, VK_IMAGE_LAYOUT_GENERAL, buffer, 1, &r);
}

/* Images uploaded and in VK_IMAGE_LAYOUT_GENERAL. */
static void scene_init(struct ct *t, struct dt *d, struct scene *s)
{
    VkImageCreateInfo info = ct_image_info(VK_IMAGE_TYPE_2D, VK_FORMAT_R32_SFLOAT, 4, 4, 1, 1, 1,
                                           VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_STORAGE_BIT |
                                               VK_IMAGE_USAGE_TRANSFER_SRC_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT);
    struct ct_image *all[5];
    VkSamplerCreateInfo si;
    VkCommandBuffer cb;
    uint32_t i, k;
    float f;

    memset(s, 0, sizeof(*s));
    for (k = 0; k < 3; k++)
        all[k] = &s->imgs[k];
    all[3] = &s->comb;
    all[4] = &s->simg;
    for (k = 0; k < 5; k++)
        ct_image(t, &d->e, &info, 0, all[k]);
    for (k = 0; k < 3; k++)
        s->imgs_view[k] = make_view(t, d, s->imgs[k].image);
    s->comb_view = make_view(t, d, s->comb.image);
    s->simg_view = make_view(t, d, s->simg.image);
    ct_host_buffer(t, &d->e, 5 * 64, VK_BUFFER_USAGE_TRANSFER_SRC_BIT, &s->staging);
    ct_host_buffer(t, &d->e, 64, VK_BUFFER_USAGE_UNIFORM_TEXEL_BUFFER_BIT, &s->utb);
    ct_host_buffer(t, &d->e, 64, VK_BUFFER_USAGE_STORAGE_TEXEL_BUFFER_BIT, &s->stb);
    ct_host_buffer(t, &d->e, 16 * 16, VK_BUFFER_USAGE_STORAGE_BUFFER_BIT, &s->out);
    ct_host_buffer(t, &d->e, 64, VK_BUFFER_USAGE_TRANSFER_DST_BIT, &s->readback);
    s->utb_view = make_texel_view(t, d, &s->utb);
    s->stb_view = make_texel_view(t, d, &s->stb);
    memset(&si, 0, sizeof(si));
    si.sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO;
    si.magFilter = si.minFilter = VK_FILTER_NEAREST;
    si.mipmapMode = VK_SAMPLER_MIPMAP_MODE_NEAREST;
    si.addressModeU = si.addressModeV = si.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    si.maxLod = VK_LOD_CLAMP_NONE;
    CT_REQUIRE_VK(t, vkCreateSampler(d->e.device, &si, NULL, &s->sampler));
    for (i = 0; i < 16; i++) {
        for (k = 0; k < 3; k++) {
            f = (float)(100 * k + i);
            memcpy(s->staging.data + 64 * k + 4 * i, &f, 4);
        }
        f = (float)(500 + i);
        memcpy(s->staging.data + 192 + 4 * i, &f, 4);
        f = (float)(900 + i);
        memcpy(s->staging.data + 256 + 4 * i, &f, 4);
        put(&s->utb, i, 7000 + i);
    }
    cb = ct_begin_commands(t, &d->e);
    for (k = 0; k < 5; k++) {
        ct_image_barrier(cb, all[k]->image, VK_IMAGE_ASPECT_COLOR_BIT, VK_IMAGE_LAYOUT_UNDEFINED,
                         VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);
        copy_region(cb, s->staging.buffer, all[k]->image, 64 * k, true);
        ct_image_barrier(cb, all[k]->image, VK_IMAGE_ASPECT_COLOR_BIT, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
                         VK_IMAGE_LAYOUT_GENERAL);
    }
    ct_submit_and_wait(t, &d->e, cb);
}

static void scene_fini(struct dt *d, struct scene *s)
{
    uint32_t k;
    for (k = 0; k < 3; k++) {
        vkDestroyImageView(d->e.device, s->imgs_view[k], NULL);
        ct_image_fini(&d->e, &s->imgs[k]);
    }
    vkDestroyImageView(d->e.device, s->comb_view, NULL);
    vkDestroyImageView(d->e.device, s->simg_view, NULL);
    ct_image_fini(&d->e, &s->comb);
    ct_image_fini(&d->e, &s->simg);
    vkDestroyBufferView(d->e.device, s->utb_view, NULL);
    vkDestroyBufferView(d->e.device, s->stb_view, NULL);
    vkDestroySampler(d->e.device, s->sampler, NULL);
    ct_buffer_fini(&d->e, &s->staging);
    ct_buffer_fini(&d->e, &s->utb);
    ct_buffer_fini(&d->e, &s->stb);
    ct_buffer_fini(&d->e, &s->out);
    ct_buffer_fini(&d->e, &s->readback);
}

/* Binds the set, dispatches spv_image_types with imgs[which], reads the
 * storage image back, and checks everything. */
static void scene_run(struct ct *t, struct dt *d, struct scene *s, VkPipeline p, VkPipelineLayout pl, VkDescriptorSet set,
                      uint32_t which)
{
    VkCommandBuffer cb = ct_begin_commands(t, &d->e);
    uint32_t i;
    vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_COMPUTE, p);
    vkCmdBindDescriptorSets(cb, VK_PIPELINE_BIND_POINT_COMPUTE, pl, 0, 1, &set, 0, NULL);
    vkCmdPushConstants(cb, pl, COMPUTE, 0, 4, &which);
    vkCmdDispatch(cb, 1, 1, 1);
    ct_image_barrier(cb, s->simg.image, VK_IMAGE_ASPECT_COLOR_BIT, VK_IMAGE_LAYOUT_GENERAL, VK_IMAGE_LAYOUT_GENERAL);
    copy_region(cb, s->readback.buffer, s->simg.image, 0, false);
    ct_host_read_barrier(cb);
    ct_submit_and_wait(t, &d->e, cb);
    for (i = 0; i < 16; i++) {
        uint32_t want[4], got[4], j;
        float f;
        want[0] = 100 * which + i;
        want[1] = 500 + i;
        want[2] = 900 + i;
        want[3] = 7000 + i;
        for (j = 0; j < 4; j++)
            got[j] = word(&s->out, 4 * i + j);
        CT_CHECKF(t, memcmp(got, want, sizeof(want)) == 0,
                  "invocation %u read sampled image %u, combined, storage image, uniform texel buffer: %u %u %u %u, "
                  "expected %u %u %u %u",
                  i, which, got[0], got[1], got[2], got[3], want[0], want[1], want[2], want[3]);
        memcpy(&f, s->readback.data + 4 * i, 4);
        CT_CHECKF(t, f == (float)(1900 + i), "storage image texel %u is %g after the store, expected %u", i, f, 1900 + i);
        CT_CHECKF(t, word(&s->stb, i) == i * 3 + 1, "storage texel buffer texel %u is %u, expected %u", i,
                  word(&s->stb, i), i * 3 + 1);
    }
}

static void scene_bindings(VkDescriptorSetLayoutBinding b[7], const VkSampler *immutable)
{
    b[0] = lb(0, SSBO, 1);
    b[1] = lb(1, VK_DESCRIPTOR_TYPE_SAMPLER, 1);
    b[2] = lb(2, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1);
    b[3] = lb(3, VK_DESCRIPTOR_TYPE_STORAGE_IMAGE, 1);
    b[4] = lb(4, VK_DESCRIPTOR_TYPE_UNIFORM_TEXEL_BUFFER, 1);
    b[5] = lb(5, VK_DESCRIPTOR_TYPE_STORAGE_TEXEL_BUFFER, 1);
    b[6] = lb(6, VK_DESCRIPTOR_TYPE_SAMPLED_IMAGE, 3);
    b[1].pImmutableSamplers = immutable;
    b[2].pImmutableSamplers = immutable;
}

static VkDescriptorPool scene_pool(struct ct *t, struct dt *d)
{
    VkDescriptorPoolSize sizes[7];
    sizes[0] = ps(SSBO, 1);
    sizes[1] = ps(VK_DESCRIPTOR_TYPE_SAMPLER, 1);
    sizes[2] = ps(VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1);
    sizes[3] = ps(VK_DESCRIPTOR_TYPE_STORAGE_IMAGE, 1);
    sizes[4] = ps(VK_DESCRIPTOR_TYPE_UNIFORM_TEXEL_BUFFER, 1);
    sizes[5] = ps(VK_DESCRIPTOR_TYPE_STORAGE_TEXEL_BUFFER, 1);
    sizes[6] = ps(VK_DESCRIPTOR_TYPE_SAMPLED_IMAGE, 3);
    return make_pool(t, d, 1, sizes, 7, 0, 0);
}

/* Writes every binding; the sampler (binding 1) only without immutable
 * samplers, the combined one with VK_NULL_HANDLE as sampler then. */
static void scene_write(struct dt *d, struct scene *s, VkDescriptorSet set, bool immutable)
{
    VkDescriptorImageInfo ii[6];
    VkDescriptorBufferInfo out = bi(&s->out, 0, VK_WHOLE_SIZE);
    VkWriteDescriptorSet w[7];
    uint32_t n = 0, k;

    memset(ii, 0, sizeof(ii));
    for (k = 0; k < 6; k++)
        ii[k].imageLayout = VK_IMAGE_LAYOUT_GENERAL;
    ii[0].sampler = s->sampler;
    ii[1].sampler = immutable ? VK_NULL_HANDLE : s->sampler;
    ii[1].imageView = s->comb_view;
    ii[2].imageView = s->simg_view;
    for (k = 0; k < 3; k++)
        ii[3 + k].imageView = s->imgs_view[k];
    w[n++] = buffer_write(set, 0, 0, SSBO, &out, 1);
    if (!immutable) {
        w[n] = buffer_write(set, 1, 0, VK_DESCRIPTOR_TYPE_SAMPLER, NULL, 1);
        w[n++].pImageInfo = &ii[0];
    }
    w[n] = buffer_write(set, 2, 0, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, NULL, 1);
    w[n++].pImageInfo = &ii[1];
    w[n] = buffer_write(set, 3, 0, VK_DESCRIPTOR_TYPE_STORAGE_IMAGE, NULL, 1);
    w[n++].pImageInfo = &ii[2];
    w[n] = buffer_write(set, 4, 0, VK_DESCRIPTOR_TYPE_UNIFORM_TEXEL_BUFFER, NULL, 1);
    w[n++].pTexelBufferView = &s->utb_view;
    w[n] = buffer_write(set, 5, 0, VK_DESCRIPTOR_TYPE_STORAGE_TEXEL_BUFFER, NULL, 1);
    w[n++].pTexelBufferView = &s->stb_view;
    w[n] = buffer_write(set, 6, 0, VK_DESCRIPTOR_TYPE_SAMPLED_IMAGE, NULL, 3);
    w[n++].pImageInfo = &ii[3];
    vkUpdateDescriptorSets(d->e.device, n, w, 0, NULL);
}

