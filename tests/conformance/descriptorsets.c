static VkDescriptorSetLayout make_layout(struct ct *t, struct dt *d, const VkDescriptorSetLayoutBinding *bindings,
                                         uint32_t count, VkDescriptorSetLayoutCreateFlags flags,
                                         const VkDescriptorBindingFlags *binding_flags)
{
    VkDescriptorSetLayoutBindingFlagsCreateInfo flags_info;
    VkDescriptorSetLayoutCreateInfo info;
    VkDescriptorSetLayout layout = VK_NULL_HANDLE;
    memset(&flags_info, 0, sizeof(flags_info));
    flags_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_BINDING_FLAGS_CREATE_INFO;
    flags_info.bindingCount = count;
    flags_info.pBindingFlags = binding_flags;
    memset(&info, 0, sizeof(info));
    info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
    info.pNext = binding_flags ? &flags_info : NULL;
    info.flags = flags;
    info.bindingCount = count;
    info.pBindings = count ? bindings : NULL;
    CT_REQUIRE_VK(t, vkCreateDescriptorSetLayout(d->e.device, &info, NULL, &layout));
    return layout;
}

