    b[2] = lb(2, SSBO, 1);
    sl = make_layout(t, &d, b, 3, 0, NULL);
    pl = make_pipeline_layout(t, &d, &sl, 1, 4);
    p = make_pipeline(t, &d, spv_inline, sizeof(spv_inline), pl);
    sizes[0] = ps(INLINE, 64);
    sizes[1] = ps(UBO, 6);
    sizes[2] = ps(SSBO, 2);
    pool = make_pool(t, &d, 2, sizes, 3, 0, 2);
    sets[0] = alloc_set(t, &d, pool, sl);
    sets[1] = alloc_set(t, &d, pool, sl);
    for (i = 0; i < 3; i++) {
        put(&small, i * step / 4, 1000 * (i + 1));
        infos[i] = bi(&small, i * step, 4);
    }
    memset(&data, 0, sizeof(data));
    data.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET_INLINE_UNIFORM_BLOCK;
    data.dataSize = sizeof(first);
    data.pData = first;
    memset(w, 0, sizeof(w));
    w[0].sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
    w[0].pNext = &data;
    w[0].dstSet = sets[0];
    w[0].dstBinding = 0;
    w[0].descriptorCount = sizeof(first);
    w[0].descriptorType = INLINE;
    w[1] = buffer_write(sets[0], 1, 0, UBO, infos, 3);
    vkUpdateDescriptorSets(d.e.device, 2, w, 0, NULL);
    data.dataSize = 4;
    data.pData = &second;
    w[0].dstArrayElement = 16;
    w[0].descriptorCount = 4;
    vkUpdateDescriptorSets(d.e.device, 1, w, 0, NULL);
    write_buffer(&d, sets[0], 2, 0, SSBO, &out, 0, 32);
    /* set 1: block bytes 0..4 written, 4..20 copied; uniform buffer 0 written, 1 and 2 copied */
    data.dataSize = 4;
    data.pData = &first[3];
    w[0].dstSet = sets[1];
    w[0].dstArrayElement = 0;
    w[0].descriptorCount = 4;
    w[1] = buffer_write(sets[1], 1, 0, UBO, infos, 1);
    vkUpdateDescriptorSets(d.e.device, 2, w, 0, NULL);
    write_buffer(&d, sets[1], 2, 0, SSBO, &out, step, 32);
    memset(&copy, 0, sizeof(copy));
    copy.sType = VK_STRUCTURE_TYPE_COPY_DESCRIPTOR_SET;
