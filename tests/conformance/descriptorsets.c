    CT_CHECKF(t, word(&out, 4) == second, "set 0, block word 4: %u", word(&out, 4));
    CT_CHECKF(t, word(&out, 5) == 3000, "set 0, uniform buffer 2: %u", word(&out, 5));
    i = (uint32_t)(step / 4);
