/* An instance and a device with every supported descriptor feature this
 * chapter uses enabled. Ends the test if the device version is below
 * `version`. */
static void dt_init(struct ct *t, struct dt *d, uint32_t version)
{
    struct ct_features en;
    VkPhysicalDeviceFeatures *c = &en.f2.features;
    const VkPhysicalDeviceFeatures *s = &d->f.f2.features;

    ct_env_init(t, &d->e);
    if (d->e.version < version)
        ct_skip(t, "needs Vulkan %u.%u; the device offers %u.%u", VK_API_VERSION_MAJOR(version),
                VK_API_VERSION_MINOR(version), VK_API_VERSION_MAJOR(d->e.version), VK_API_VERSION_MINOR(d->e.version));
    ct_get_features(&d->e, &d->f, 0);
    ct_get_features(&d->e, &en, 0); /* for the chain */
    memset(c, 0, sizeof(*c));
    c->shaderUniformBufferArrayDynamicIndexing = s->shaderUniformBufferArrayDynamicIndexing;
    c->shaderSampledImageArrayDynamicIndexing = s->shaderSampledImageArrayDynamicIndexing;
    c->shaderStorageBufferArrayDynamicIndexing = s->shaderStorageBufferArrayDynamicIndexing;
    c->shaderStorageImageArrayDynamicIndexing = s->shaderStorageImageArrayDynamicIndexing;
    if (d->e.version >= VK_API_VERSION_1_2) {
        memset(&en.v11.storageBuffer16BitAccess, 0, sizeof(en.v11) - offsetof(VkPhysicalDeviceVulkan11Features, storageBuffer16BitAccess));
        memset(&en.v12.samplerMirrorClampToEdge, 0, sizeof(en.v12) - offsetof(VkPhysicalDeviceVulkan12Features, samplerMirrorClampToEdge));
        en.v12.shaderStorageBufferArrayNonUniformIndexing = d->f.v12.shaderStorageBufferArrayNonUniformIndexing;
        en.v12.descriptorBindingUniformBufferUpdateAfterBind = d->f.v12.descriptorBindingUniformBufferUpdateAfterBind;
        en.v12.descriptorBindingStorageBufferUpdateAfterBind = d->f.v12.descriptorBindingStorageBufferUpdateAfterBind;
        en.v12.descriptorBindingPartiallyBound = d->f.v12.descriptorBindingPartiallyBound;
        en.v12.descriptorBindingVariableDescriptorCount = d->f.v12.descriptorBindingVariableDescriptorCount;
        en.v12.runtimeDescriptorArray = d->f.v12.runtimeDescriptorArray;
    }
    if (d->e.version >= VK_API_VERSION_1_3) {
        memset(&en.v13.robustImageAccess, 0, sizeof(en.v13) - offsetof(VkPhysicalDeviceVulkan13Features, robustImageAccess));
        en.v13.inlineUniformBlock = d->f.v13.inlineUniformBlock;
    }
    if (d->e.version >= VK_API_VERSION_1_4) {
        memset(&en.v14.globalPriorityQuery, 0, sizeof(en.v14) - offsetof(VkPhysicalDeviceVulkan14Features, globalPriorityQuery));
        en.v14.pushDescriptor = d->f.v14.pushDescriptor;
    }
    ct_env_device(t, &d->e, &en.f2);
}

