/* Inline every quoted #include reachable from the root header into one file.
 *
 *   amalgamate ROOT [-I DIR]... [--license FILE]... -o OUTPUT
 *
 * Each file is inlined at most once (include-once semantics). Angle-bracket
 * includes (<stdio.h>, <objc/runtime.h>, ...) are left alone: they are system
 * headers. A quoted include that cannot be resolved is an error, so the
 * output is guaranteed to be self-contained.
 */
#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "tool.h"

#define MAX_LIST 256

static const char *include_dirs[MAX_LIST];
static int include_dir_count;
static char *seen[4096];
static int seen_count;
static char repo[PATH_MAX];
static struct buf out;

static int was_seen(const char *path)
{
    int i;
    for (i = 0; i < seen_count; i++)
        if (strcmp(seen[i], path) == 0)
            return 1;
    return 0;
}

static const char *rel(const char *path)
{
    size_t n = strlen(repo);
    if (strncmp(path, repo, n) == 0 && path[n] == '/')
        return path + n + 1;
    return path;
}

/* Returns the realpath of NAME found in FROM_DIR or an include dir, or NULL. */
static char *resolve(const char *name, const char *from_dir)
{
    char candidate[PATH_MAX], resolved[PATH_MAX];
    int i;
    for (i = -1; i < include_dir_count; i++) {
        FILE *f;
        snprintf(candidate, sizeof(candidate), "%s/%s", i < 0 ? from_dir : include_dirs[i], name);
        if (!realpath(candidate, resolved) || !(f = fopen(resolved, "r")))
            continue;
        fclose(f);
        return xstrdup(resolved);
    }
    return NULL;
}

/* Matches `#include "NAME"`; returns NAME (in a static buffer) or NULL. */
static const char *quoted_include(const char *line)
{
    static char name[PATH_MAX];
    const char *p = skip_space(line), *end;
    if (*p != '#')
        return NULL;
    p = skip_space(p + 1);
    if (strncmp(p, "include", 7) != 0)
        return NULL;
    p = skip_space(p + 7);
    if (*p != '"' || !(end = strchr(p + 1, '"')) || (size_t)(end - p - 1) >= sizeof(name))
        return NULL;
    memcpy(name, p + 1, (size_t)(end - p - 1));
    name[end - p - 1] = '\0';
    return name;
}

static int is_pragma_once(const char *line)
{
    const char *p = skip_space(line);
    if (*p != '#')
        return 0;
    p = skip_space(p + 1);
    if (strncmp(p, "pragma", 6) != 0 || (p[6] != ' ' && p[6] != '\t'))
        return 0;
    p = skip_space(p + 6);
    return strncmp(p, "once", 4) == 0 && !is_ident(p[4]);
}

static void inline_file(const char *path)
{
    char *text = read_file(path), *line, *next, dir[PATH_MAX];
    int lineno = 0;

    seen[seen_count++] = xstrdup(path);
    parent_dir(dir, sizeof(dir), path);
    buf_printf(&out, "/* ---- begin %s ---- */\n", rel(path));

    for (line = text; *line; line = next) {
        const char *name;
        char *nl = strchr(line, '\n'), saved;
        next = nl ? nl + 1 : line + strlen(line);
        saved = *next;
        *next = '\0'; /* line now includes its newline */
        lineno++;

        if (is_pragma_once(line)) {
            /* dropped */
        } else if ((name = quoted_include(line))) {
            char *target = resolve(name, dir);
            if (!target)
                die("%s:%d: cannot resolve \"%s\"", rel(path), lineno, name);
            if (!was_seen(target))
                inline_file(target);
            free(target);
        } else {
            buf_puts(&out, line);
        }
        *next = saved;
    }
    buf_printf(&out, "/* ---- end %s ---- */\n", rel(path));
    free(text);
}

int main(int argc, char **argv)
{
    const char *licenses[MAX_LIST], *root_arg = NULL, *output = NULL;
    char root[PATH_MAX], outdir[PATH_MAX];
    int license_count = 0, i;

    for (i = 1; i < argc; i++) {
        if (strcmp(argv[i], "-I") == 0 && i + 1 < argc && include_dir_count < MAX_LIST)
            include_dirs[include_dir_count++] = argv[++i];
        else if (strcmp(argv[i], "--license") == 0 && i + 1 < argc && license_count < MAX_LIST)
            licenses[license_count++] = argv[++i];
        else if (strcmp(argv[i], "-o") == 0 && i + 1 < argc)
            output = argv[++i];
        else if (!root_arg)
            root_arg = argv[i];
        else
            die("usage: amalgamate ROOT [-I DIR]... [--license FILE]... -o OUTPUT");
    }
    if (!root_arg || !output)
        die("usage: amalgamate ROOT [-I DIR]... [--license FILE]... -o OUTPUT");

    parent_dir(outdir, sizeof(outdir), output);
    if (!realpath(outdir, repo))
        die("cannot resolve directory of %s", output);
    if (!realpath(root_arg, root))
        die("cannot open %s", root_arg);

    buf_puts(&out, "/* GENERATED by tools/amalgamate.c - edit the files under src/ instead. */\n");
    inline_file(root);

    for (i = 0; i < license_count; i++) {
        char *body = read_file(licenses[i]), *p;
        size_t n = strlen(body);
        while (n && (body[n - 1] == '\n' || body[n - 1] == ' ' || body[n - 1] == '\t'))
            body[--n] = '\0';
        buf_puts(&out, "\n/*\n");
        for (p = body; *p; p++) {
            buf_putc(&out, *p);
            if (p[0] == '*' && p[1] == '/')
                buf_putc(&out, ' '); /* keep the comment open */
        }
        buf_puts(&out, "\n*/\n");
        free(body);
    }

    write_file(output, &out);
    return 0;
}
